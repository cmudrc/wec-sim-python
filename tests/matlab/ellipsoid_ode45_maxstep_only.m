% Diagnose the published ellipsoid ode45 solver step without changing force clocks.
% Invoke as a script in the base workspace, as WEC-Sim's wecSim.m is invoked:
%   waveCase = 'Regular'; mode = 'published'; ellipsoid_ode45_maxstep_only
assert(any(strcmp(mode, {'published', 'maxstep005'})));
assert(any(strcmp(waveCase, {'Regular', 'RegularCIC'})));
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
sourceDir = fullfile(repoRoot, 'matlab-ref', 'source');
hydroDir = fullfile(repoRoot, 'applications', 'Nonlinear_Hydro', 'hydroData');
caseDir = fullfile(repoRoot, 'applications', 'Nonlinear_Hydro', 'ode45', waveCase);
addpath(genpath(sourceDir));
cd(hydroDir);
if ~isfile('ellipsoid.h5')
    bemio;
end
cd(caseDir);
run('initializeWecSim');
assert(strcmp(simu.solver, 'ode45') && abs(simu.dt - 0.05) < 1e-12 && ...
    abs(simu.dtOut - 0.05) < 1e-12 && ...
    abs(simu.nonlinearDt - 0.05) < 1e-12 && ...
    abs(simu.cicDt - 0.05) < 1e-12 && ...
    simu.endTime == 150 && simu.rampTime == 50, ...
    'Pinned published sample settings changed');
model = 'ellipsoid';
assert(abs(str2double(get_param(model, 'MaxStep')) - 0.05) < 1e-12);
if strcmp(mode, 'maxstep005')
    set_param(model, 'MaxStep', '0.005');
end
step = str2double(get_param(model, 'MaxStep'));
assert(abs(step - (0.005 * strcmp(mode, 'maxstep005') + ...
                    0.05 * strcmp(mode, 'published'))) < 1e-12);
fprintf('SOURCE_SETTINGS case=%s mode=%s dt=%.9g dtOut=%.9g nonlinearDt=%.9g cicDt=%.9g MaxStep=%.9g\n', ...
    waveCase, mode, simu.dt, simu.dtOut, simu.nonlinearDt, simu.cicDt, step);
sim(simu.simMechanicsFile, [], simset('SrcWorkspace', 'parent'));
assert(abs(str2double(get_param(model, 'MaxStep')) - step) < 1e-12, ...
    'Simulink changed the prescribed MaxStep during the run');
run('stopWecSim');
bodyRecord = output.bodies(1);
bodyValues = [bodyRecord.time(:), bodyRecord.position, ...
    bodyRecord.velocity, bodyRecord.forceTotal, ...
    bodyRecord.forceExcitation, bodyRecord.forceRadiationDamping, ...
    bodyRecord.forceAddedMass, bodyRecord.forceRestoring, ...
    bodyRecord.forceMorisonAndViscous, bodyRecord.acceleration];
ptoRecord = output.ptos(1);
ptoValues = [ptoRecord.time(:), ptoRecord.position, ...
    ptoRecord.velocity, ptoRecord.forceInternalMechanics, ...
    ptoRecord.powerInternalMechanics];
waveValues = [output.wave.time(:), output.wave.elevation(:)];
assert(size(bodyValues, 1) == 3001 && size(bodyValues, 2) == 55 && ...
    size(ptoValues, 1) == 3001 && size(ptoValues, 2) == 25 && ...
    size(waveValues, 1) == 3001 && size(waveValues, 2) == 2 && ...
    all(isfinite(bodyValues), 'all') && all(isfinite(ptoValues), 'all') && ...
    all(isfinite(waveValues), 'all'), 'Incomplete source output');
outDir = fullfile(repoRoot, 'matlab-ellipsoid-ode45-maxstep', waveCase);
if ~isfolder(outDir)
    mkdir(outDir);
end
writematrix(bodyValues, fullfile(outDir, [mode '_body.csv']));
writematrix(ptoValues, fullfile(outDir, [mode '_pto.csv']));
writematrix(waveValues, fullfile(outDir, [mode '_wave.csv']));
writematrix([simu.dt, simu.dtOut, simu.nonlinearDt, simu.cicDt, step], ...
    fullfile(outDir, [mode '_settings.csv']));
close_system(model, 0);
