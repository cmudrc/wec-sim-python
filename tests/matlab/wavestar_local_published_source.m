function wavestar_local_published_source(coreDir, applicationsDir, repoDir, outDir, commandMat)
% Run the pinned 225 s WaveStar input with its real MATLAB toolboxes.
% Work in a disposable application copy. Geometry filename case and the
% post-run plotting script are the only edits for an ordinary source run.
% Supplying commandMat replaces active NMPC torque requests with that saved
% request series while the source independently advances the plant.
assert(~isfolder(outDir), 'Use a fresh WaveStar output directory');
mkdir(outDir);
source = fullfile(applicationsDir, 'WECCCOMP');
scratch = fullfile(outDir, 'WECCCOMP');
[copied, message] = copyfile(source, scratch);
assert(copied, message);
[copied, message] = copyfile(fullfile(repoDir, 'tests', 'fixtures', ...
    'matlab', 'wavestar_fixed_input_step', 'wavestar.h5'), ...
    fullfile(scratch, 'hydroData', 'wavestar.h5'));
assert(copied, message);
caseDir = fullfile(scratch, 'WECCCOMP_Nonlinear_Model_Predictive');
inputFile = fullfile(caseDir, 'wecSimInputFile.m');
input = fileread(inputFile);
assert(contains(input, 'simu.dt             = 50/1000;') && ...
    contains(input, "simu.solver         = 'ode8';") && ...
    contains(input, 'simu.cicEndTime     = 2;'), ...
    'The pinned WaveStar time settings changed');
for name = ["Float", "Arm", "Frame", "BC", "Motor"]
    oldName = name + '.stl';
    newName = name + '.STL';
    assert(contains(input, oldName) && ...
        isfile(fullfile(scratch, 'geometry', char(newName))), ...
        'The pinned WaveStar geometry name changed');
    input = strrep(input, char(oldName), char(newName));
end
write_text(inputFile, input);
plotFile = fullfile(caseDir, 'userDefinedFunctions.m');
assert(contains(fileread(plotFile), 'ii = find(Output_power.time==25);'), ...
    'The pinned post-run plotting script changed');
write_text(plotFile, '% Post-run plotting disabled for this batch audit.');
if nargin >= 5 && ~isempty(commandMat)
    assert(isfile(commandMat), 'The prescribed command MAT file is missing');
    saved = load(commandMat, 'codexCommand');
    assert(isfield(saved, 'codexCommand') && ...
        isequal(size(saved.codexCommand), [4201, 1]) && ...
        all(isfinite(saved.codexCommand)), ...
        'Expected one finite command for each active 50 ms NMPC sample');
    controllerFile = fullfile(caseDir, 'NMPC.m');
    controller = fileread(controllerFile);
    target = '    y = Ubar;';
    assert(count(controller, target) == 1, 'Pinned NMPC output changed');
    commandPath = strrep(char(commandMat), '''', '''''');
    replacement = sprintf([ ...
        '    y = Ubar;\n' ...
        '    persistent codexCommand codexCall;\n' ...
        '    if isempty(codexCommand)\n' ...
        '        saved = load(''%s'', ''codexCommand'');\n' ...
        '        codexCommand = saved.codexCommand;\n' ...
        '        codexCall = 0;\n' ...
        '    end\n' ...
        '    codexCall = codexCall + 1;\n' ...
        '    y(1) = codexCommand(codexCall);\n'], commandPath);
    write_text(controllerFile, strrep(controller, target, replacement));
end

assert(~isempty(which('quadprog')) && ~isempty(which('dlqr')) && ...
    ~isempty(which('regress')) && ~isempty(which('ar')) && ...
    ~isempty(which('forecast')), 'The source MATLAB toolboxes are missing');
addpath(genpath(fullfile(coreDir, 'source')));
cd(caseDir);
wecSim;
assert(strcmp(simu.solver, 'ode8') && simu.dt == 0.05 && ...
    simu.endTime == 225 && simu.rampTime == 25 && ...
    simu.stateSpace == 1 && simu.cicEndTime == 2 && ...
    strcmp(waves.type, 'irregular') && ...
    strcmp(waves.spectrumType, 'JS') && ...
    waves.height == 0.1042 && waves.period == 1.836 && ...
    waves.gamma == 3.3 && waves.phaseSeed == 1 && ...
    controllerType == 2 && predictionType == 2 && ...
    Np == 40 && startController == 15 && startPredictor == 10 && ...
    numel(output.bodies) == 5 && numel(output.ptos) == 1, ...
    'The published WaveStar inputs changed');

b = output.bodies(1);
p = output.ptos(1);
body = [b.time(:), b.position, b.velocity, b.forceTotal, b.forceExcitation];
pto = [p.time(:), p.position, p.velocity, p.forceInternalMechanics, ...
    p.powerInternalMechanics, p.forceTotal, p.forceActuation, p.acceleration];
components = [waves.omega(:), waves.amplitude(:), ...
    waves.dOmega(:), waves.phase(:)];
wave = [output.wave.time(:), output.wave.elevation(:)];
assert(isequal(size(body), [4501, 25]) && ...
    isequal(size(pto), [4501, 43]) && ...
    isequal(size(components), [500, 4]) && ...
    isequal(size(wave), [4501, 2]) && ...
    all(isfinite(body), 'all') && all(isfinite(pto), 'all'), ...
    'The published WaveStar output is incomplete');
writematrix(body, fullfile(outDir, 'body.csv'));
writematrix(pto, fullfile(outDir, 'pto.csv'));
writematrix(components, fullfile(outDir, 'components.csv'));
writematrix(wave, fullfile(outDir, 'wave.csv'));
save(fullfile(outDir, 'controller.mat'), 'cmd_ptoM', ...
    'Output_power', 'Output_energy', 'estimated_states', ...
    'AR_excM_pred', '-v7');
fprintf('LOCAL_WAVESTAR_SOURCE_PASSED samples=%d\n', numel(b.time));
end

function write_text(path, value)
file = fopen(path, 'w');
assert(file ~= -1, 'Could not write disposable WaveStar file');
cleanup = onCleanup(@() fclose(file));
fprintf(file, '%s', value);
end
