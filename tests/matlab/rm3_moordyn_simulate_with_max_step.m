% Pinned wecSim.m sequence with only MaxStep overridden after initialization.
run('initializeWecSim');
assert(abs(simu.dt - couplingStep) < 1e-12 && ...
    simu.dtOut == 0.01 && simu.endTime == 10 && ...
    strcmp(simu.solver, 'ode45') && waves.phaseSeed == 1 && ...
    mooring(1).moorDyn == 1, 'Audit settings changed');
[~, modelName, ~] = fileparts(simu.simMechanicsFile);
set_param(modelName, 'MaxStep', num2str(maximumStep, '%.15g'));
assert(abs(str2double(get_param(modelName, 'MaxStep')) - maximumStep) < 1e-12, ...
    'Could not set the independent ode45 maximum step');
if ~isempty(relativeTolerance)
    assert(abs(str2double(get_param(modelName, 'RelTol')) - 1e-3) < 1e-12, ...
        'Pinned source default ode45 tolerance changed');
    set_param(modelName, 'RelTol', num2str(relativeTolerance, '%.15g'));
    assert(abs(str2double(get_param(modelName, 'RelTol')) ...
        - relativeTolerance) < 1e-12, ...
        'Could not set the independent ode45 relative tolerance');
end
sim(simu.simMechanicsFile, [], simset('SrcWorkspace', 'parent'));
run('stopWecSim');
