% Pinned wecSim.m sequence with only ode4 FixedStep overridden after setup.
run('initializeWecSim');
assert(simu.dt == 0.1 && simu.dtOut == 0.1 && ...
    simu.cicDt == 0.1 && simu.nonlinearDt == 0.1 && ...
    simu.endTime == 120 && simu.rampTime == 40 && ...
    simu.pressure == 0 && simu.paraview.option == 0 && ...
    strcmp(simu.solver, 'ode4') && ...
    strcmp(waves.type, 'regular') && waves.height == 2.5 && ...
    waves.period == 8 && body(1).nonlinearHydro == 2 && ...
    body(1).mass == 127000 && pto(1).damping == 0 && ...
    pto(1).stiffness == 0, ...
    'Published OSWEC grids or physics changed');
[~, modelName, ~] = fileparts(simu.simMechanicsFile);
assert(abs(str2double(get_param(modelName, 'FixedStep')) - 0.1) < 1e-12, ...
    'Published fixed solver step changed');
set_param(modelName, 'FixedStep', '0.0125');
fixedStep = str2double(get_param(modelName, 'FixedStep'));
assert(abs(fixedStep - 0.0125) < 1e-12, ...
    'Could not set the independent fixed solver step');
sim(simu.simMechanicsFile, [], simset('SrcWorkspace', 'parent'));
run('stopWecSim');
