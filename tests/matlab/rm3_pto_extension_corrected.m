function rm3_pto_extension_corrected(caseName)
% Regenerate a copied-input corrected validation baseline for either 30 s
% RM3 PTO-extension free decay. Pinned upstream checkouts are never edited.
caseName = string(caseName);
assert(isscalar(caseName) && any(caseName == ["float", "spar"]), ...
    'Select the float or spar PTO-extension case');
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
    'RM3', 'hydroData');
cd(hydroDir);
if ~isfile('rm3.h5')
    bemio;
end

sourceDir = fullfile(repoRoot, 'applications', 'RM3_PTO_Extension', caseName);
original = fileread(fullfile(sourceDir, 'wecSimInputFile.m'));
assert(count(string(original), "simu.dt = 0.1;") == 1 && ...
    contains(original, 'simu.endTime = 30;') && ...
    contains(original, "waves = waveClass('noWaveCIC');") && ...
    contains(original, 'pto(1).extension.PositionTargetValue = 5;') && ...
    ~contains(original, 'simu.dtOut =') && ...
    ~contains(original, 'simu.cicDt ='), ...
    'Pinned RM3 PTO-extension input changed');

outDir = fullfile(repoRoot, 'matlab-rm3-pto-corrected', caseName);
assert(~isfolder(outDir), 'Corrected PTO-extension output already exists');
mkdir(outDir);
steps = [0.0015625, 0.00078125];
labels = ["0p0015625", "0p00078125"];
settings = zeros(2, 6);
for index = 1:2
    dt = steps(index);
    % Keep the copied model at the original two-level depth so relative
    % links to the pinned common RM3 hydrodynamics remain valid.
    caseDir = fullfile(fileparts(sourceDir), ...
        caseName + "_corrected_" + labels(index));
    assert(~isfolder(caseDir), 'Disposable corrected case already exists');
    mkdir(caseDir);
    copyfile(fullfile(sourceDir, 'RM3.slx'), fullfile(caseDir, 'RM3.slx'));
    inputFile = fullfile(caseDir, 'wecSimInputFile.m');
    contents = strrep(original, 'simu.dt = 0.1;', ...
        sprintf('simu.dt = %.8f;', dt));
    fid = fopen(inputFile, 'w');
    assert(fid > 0, 'Cannot write corrected disposable input');
    fwrite(fid, contents);
    fclose(fid);

    cd(caseDir);
    wecSim;
    assert(strcmp(simu.solver, 'ode4') && abs(simu.dt - dt) < 1e-12 && ...
        abs(simu.dtOut - dt) < 1e-12 && ...
        abs(simu.cicDt - dt) < 1e-12 && ...
        abs(simu.nonlinearDt - dt) < 1e-12 && ...
        simu.endTime == 30 && strcmp(waves.type, 'noWaveCIC') && ...
        pto(1).damping == 0 && pto(1).stiffness == 0 && ...
        pto(1).extension.PositionTargetValue == 5, ...
        'Corrected run changed a physical input or sample clock');
    fixedStep = str2double(get_param('RM3', 'FixedStep'));
    assert(abs(fixedStep - dt) < 1e-12, ...
        'Simulink fixed step differs from corrected input');
    settings(index, :) = [simu.dt, simu.dtOut, simu.cicDt, ...
        simu.nonlinearDt, fixedStep, simu.endTime];

    float = output.bodies(1);
    spar = output.bodies(2);
    ptoRecord = output.ptos(1);
    values = [float.time(:), float.position(:, 3), ...
        float.velocity(:, 3), spar.position(:, 3), ...
        spar.velocity(:, 3), ptoRecord.position(:, 3), ...
        ptoRecord.velocity(:, 3), ...
        ptoRecord.forceInternalMechanics(:, 3), ...
        ptoRecord.powerInternalMechanics(:, 3)];
    countSamples = round(30 / dt) + 1;
    assert(isequal(size(values), [countSamples, 9]) && ...
        all(isfinite(values), 'all') && ...
        max(abs(values(:, 1) - (0:countSamples - 1)' * dt)) < 1e-9 && ...
        max(abs(values(:, 8:9)), [], 'all') < 1e-7, ...
        'Incomplete corrected source or nonzero published PTO');
    writematrix(values, fullfile(outDir, labels(index) + ".csv"));
    if index == 2
        writematrix([float.time(:), float.position, float.velocity], ...
            fullfile(outDir, labels(index) + "_float_body.csv"));
        writematrix([spar.time(:), spar.position, spar.velocity], ...
            fullfile(outDir, labels(index) + "_spar_body.csv"));
    end
    close_system('RM3', 0);
    clear output;
end
writematrix(settings, fullfile(outDir, 'settings.csv'));
end
