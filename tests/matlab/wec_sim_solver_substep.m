% Run the pinned WaveStar model with its 50 ms WEC-Sim inputs unchanged.
% Only Simulink's ode8 fixed step changes, including in the full NMPC case.
run('initializeWecSim');

[~, modelName] = fileparts(simu.simMechanicsFile);
assert(strcmp(simu.solver, 'ode8') && simu.dt == 0.05 && ...
    simu.dtOut == 0.05 && abs(dt - 0.05) < 1e-12 && ...
    strcmp(get_param(modelName, 'Solver'), 'ode8') && ...
    abs(str2double(get_param(modelName, 'FixedStep')) - 0.05) < 1e-12 && ...
    ismember(stepOverride, [0.05, 0.025, 0.0125]), ...
    'The published input, controller rate, or initial solver changed');
set_param(modelName, 'FixedStep', num2str(stepOverride, '%.17g'), ...
    'MaxStep', num2str(stepOverride, '%.17g'));
assert(abs(str2double(get_param(modelName, 'FixedStep')) - ...
    stepOverride) < 1e-12, 'The internal solver step was not applied');

sim(simu.simMechanicsFile, [], simset('SrcWorkspace', 'parent'));
run('stopWecSim');
