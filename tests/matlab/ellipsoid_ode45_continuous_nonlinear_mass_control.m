% Heave-only no-active-delay control for the 150 s continuous-nonlinear arm.
% Invoke as a script with waveCase = 'Regular' or 'RegularCIC'.
assert(any(strcmp(waveCase, {'Regular', 'RegularCIC'})));
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
sourceDir = fullfile(repoRoot, 'matlab-ref', 'source');
appDir = fullfile(repoRoot, 'applications', 'Nonlinear_Hydro');
hydroDir = fullfile(appDir, 'hydroData');
originalDir = fullfile(appDir, 'ode45', waveCase);
addpath(genpath(sourceDir));
cd(hydroDir);
if ~isfile('ellipsoid.h5')
    bemio;
end

% Match PR #658's heave mass identity. This shifts exactly A_zz into the
% body's rigid mass, leaving m + A_zz unchanged and the active delayed
% added-mass coefficient zero. The 100 ns Simulink delay remains present.
hydro = readBEMIOH5(fullfile(hydroDir, 'ellipsoid.h5'), 1, 0);
if strcmp(waveCase, 'Regular')
    omega = 2*pi/6;
    frequencies = hydro.simulation_parameters.w;
    diagonal = zeros(3, 1);
    for axis = 1:3
        diagonal(axis) = interp1(frequencies, ...
            squeeze(hydro.hydro_coeffs.added_mass.all(axis, axis, :)), ...
            omega, 'spline');
    end
else
    matrix = hydro.hydro_coeffs.added_mass.inf_freq;
    diagonal = diag(matrix(1:3, 1:3));
end
factor = diagonal(3)/sum(diagonal);
assert(isfinite(factor) && factor > 0 && factor < 1, ...
    'The pinned heave-only added-mass coefficient is invalid');

original = fileread(fullfile(originalDir, 'wecSimInputFile.m'));
assert(contains(original, 'simu.solver=''ode45'';') && ...
    contains(original, 'simu.dt = 0.05;') && ...
    contains(original, 'simu.endTime=150;') && ...
    contains(original, 'body(1).nonlinearHydro = 2;') && ...
    ~contains(original, 'simu.dtOut') && ...
    ~contains(original, 'simu.nonlinearDt') && ...
    ~contains(original, 'simu.cicDt') && ...
    ~contains(original, 'body(1).adjMassFactor'), ...
    'The pinned published input has changed');
caseDir = fullfile(fileparts(originalDir), ...
    [waveCase '_continuous_nonlinear_mass_control']);
assert(~isfolder(caseDir), 'Disposable mass-control case already exists');
mkdir(caseDir);
copyfile(fullfile(originalDir, 'ellipsoid.slx'), ...
    fullfile(caseDir, 'ellipsoid.slx'));
corrected = strrep(original, 'body(1).nonlinearHydro = 2;', sprintf( ...
    ['body(1).nonlinearHydro = 2;\n' ...
     'body(1).adjMassFactor = %.17g; %% heave-only exact mass shift'], factor));
assert(~strcmp(corrected, original) && ...
    contains(corrected, 'body(1).adjMassFactor = ') && ...
    contains(corrected, 'simu.dt = 0.05;'), ...
    'The copied input did not receive only the mass factor');
fid = fopen(fullfile(caseDir, 'wecSimInputFile.m'), 'w');
assert(fid > 0, 'Could not write disposable mass-control input');
fprintf(fid, '%s', corrected);
fclose(fid);
assert(strcmp(fileread(fullfile(caseDir, 'wecSimInputFile.m')), corrected));

cd(caseDir);
run('initializeWecSim');
assert(strcmp(simu.solver, 'ode45') && ...
    abs(simu.dt - .05) < 1e-12 && ...
    abs(simu.dtOut - .05) < 1e-12 && ...
    abs(simu.nonlinearDt - .05) < 1e-12 && ...
    abs(simu.cicDt - .05) < 1e-12 && ...
    simu.endTime == 150 && simu.rampTime == 50 && ...
    abs(body(1).adjMassFactor - factor) < 1e-12, ...
    'A published clock, duration, or derived mass factor changed');
model = 'ellipsoid';
assert(abs(str2double(get_param(model, 'MaxStep')) - .05) < 1e-12 && ...
    abs(str2double(get_param(model, 'StopTime')) - 150) < 1e-12);
delayBlock = [model '/Rigid Body/Hydrodynamic Body/Transport Delay'];
assert(abs(str2double(get_param(delayBlock, 'DelayTime')) - 1e-7) < 1e-16, ...
    'The copied model has an unexpected core delay');

force = body(1).hydroForce.hf1;
originalMass = force.storage.fAddedMass;
assert(abs(originalMass(3,3) - simu.rho*diagonal(3)) < 1e-7, ...
    'The HDF5 and initialized heave added mass differ');
assert(abs(sum(diag(originalMass(1:3,1:3)))*factor - ...
    originalMass(3,3)) < 1e-7);
assert(abs(force.fAddedMass(3,3)) < 1e-7, ...
    'Active heave acceleration still passes through the delay');
assert(abs(force.adjustedMass - (force.mass + originalMass(3,3))) < 1e-7, ...
    'The corrected heave mass is not m + A_zz');
inactive = [1 2 4 5 6];
massRecord = [factor, sum(diag(originalMass(1:3,1:3))), ...
    originalMass(3,3), force.mass, force.adjustedMass, ...
    force.fAddedMass(3,3), .05, force.fAddedMass(3,inactive)];

% Apply exactly the three continuous nonlinear evaluations in the
% published-clock timing arm, in a disposable copy of the application model.
bodyLink = [model '/Rigid Body'];
if ~strcmp(get_param(bodyLink, 'LinkStatus'), 'none')
    set_param(bodyLink, 'LinkStatus', 'none');
end
hydroLink = [bodyLink '/Hydrodynamic Body'];
if ~strcmp(get_param(hydroLink, 'LinkStatus'), 'none')
    set_param(hydroLink, 'LinkStatus', 'none');
end
restoringBlock = [hydroLink ...
    '/Hydrostatic Restoring Force Calculation' ...
    '/Linear and Nonlinear Restoring Force Variant Subsystem' ...
    '/Nonlinear Hydrostatic Restoring Force/Restoring Forces'];
fkBlock = [hydroLink ...
    '/Wave Diffraction and Excitation Force Calculation' ...
    '/Nonlinear FK Force Variant Subsystem' ...
    '/With Nonlinear FroudeKrylov Force'];
waveBlock = [hydroLink '/Nonlinear Wave Elevation'];
blocks = {restoringBlock, fkBlock, waveBlock};
for iBlock = 1:numel(blocks)
    assert(strcmp(get_param(blocks{iBlock}, 'TreatAsAtomicUnit'), 'on') && ...
        strcmp(get_param(blocks{iBlock}, 'SystemSampleTime'), ...
               'simu.nonlinearDt'), ...
        'A pinned nonlinear sample-time block changed');
    set_param(blocks{iBlock}, 'SystemSampleTime', '0');
    assert(strcmp(get_param(blocks{iBlock}, 'SystemSampleTime'), '0'));
end
set_param(model, 'SimulationCommand', 'update');
compiledPeriod = zeros(1, numel(blocks));
for iBlock = 1:numel(blocks)
    sample = get_param(blocks{iBlock}, 'CompiledSampleTime');
    fprintf('COMPILED_SAMPLE_TIMES case=%s block=%d\n', waveCase, iBlock);
    disp(sample);
    if ~iscell(sample)
        sample = {sample};
    end
    rates = zeros(1, numel(sample));
    for iRate = 1:numel(sample)
        pair = sample{iRate};
        if ischar(pair) || isstring(pair)
            pair = str2num(char(pair)); %#ok<ST2NM> compiled Simulink value
        end
        assert(isnumeric(pair) && numel(pair) == 2 && ...
            abs(pair(2)) < 1e-12, ...
            'Nonlinear block has an unparseable compiled sample time');
        rates(iRate) = pair(1);
    end
    assert(any(abs(rates) < 1e-12), ...
        'Continuous nonlinear sample period is absent from compiled rates');
    compiledPeriod(iBlock) = rates(find(abs(rates) < 1e-12, 1));
end
assert(abs(str2double(get_param(model, 'MaxStep')) - .05) < 1e-12 && ...
    abs(str2double(get_param(delayBlock, 'DelayTime')) - 1e-7) < 1e-16 && ...
    abs(str2double(get_param(model, 'StopTime')) - 150) < 1e-12, ...
    'The published solver, feedback delay, or duration changed');
fprintf(['CONTINUOUS_NONLINEAR_MASS_CONTROL case=%s factor=%.17g ' ...
    'activeAddedMass=%.9g residual=%.9g effectiveMass=%.9g ' ...
    'dt=%.9g dtOut=%.9g nonlinearDt=%.9g cicDt=%.9g MaxStep=%.9g\n'], ...
    waveCase, factor, originalMass(3,3), force.fAddedMass(3,3), ...
    force.adjustedMass, simu.dt, simu.dtOut, simu.nonlinearDt, ...
    simu.cicDt, str2double(get_param(model, 'MaxStep')));

sim(simu.simMechanicsFile, [], simset('SrcWorkspace', 'parent'));
assert(abs(str2double(get_param(model, 'MaxStep')) - .05) < 1e-12 && ...
    abs(str2double(get_param(model, 'StopTime')) - 150) < 1e-12, ...
    'Simulink changed the published model settings');
run('stopWecSim');
record = output.bodies(1);
% responseClass postprocessing recomputes reported added mass. The storage
% field below retains the force that actually passed the Simulink delay.
appliedValues = [record.time(:), ...
    body(1).hydroForce.hf1.storage.output_forceAddedMass];
bodyValues = [record.time(:), record.position, record.velocity, ...
    record.forceTotal, record.forceExcitation, ...
    record.forceRadiationDamping, record.forceAddedMass, ...
    record.forceRestoring, record.forceMorisonAndViscous, ...
    record.acceleration];
pto = output.ptos(1);
ptoValues = [pto.time(:), pto.position, pto.velocity, ...
    pto.forceInternalMechanics, pto.powerInternalMechanics];
waveValues = [output.wave.time(:), output.wave.elevation(:)];
inactiveAcceleration = record.acceleration(:, inactive);
crossHeaveForce = inactiveAcceleration * force.fAddedMass(3, inactive)';
assert(isequal(size(bodyValues), [3001, 55]) && ...
    isequal(size(appliedValues), [3001, 7]) && ...
    isequal(size(ptoValues), [3001, 25]) && ...
    isequal(size(waveValues), [3001, 2]) && ...
    max(abs(bodyValues(:, 1) - (0:3000)' * .05)) < 1e-9 && ...
    max(abs(appliedValues(:, 1) - bodyValues(:, 1))) < 1e-9 && ...
    max(abs(ptoValues(:, 1) - bodyValues(:, 1))) < 1e-9 && ...
    max(abs(waveValues(:, 1) - bodyValues(:, 1))) < 1e-9 && ...
    all(isfinite(bodyValues), 'all') && ...
    all(isfinite(appliedValues), 'all') && ...
    all(isfinite(ptoValues), 'all') && ...
    all(isfinite(waveValues), 'all') && ...
    max(abs(record.velocity(:, inactive)), [], 'all') < 1e-9 && ...
    max(abs(inactiveAcceleration), [], 'all') < 1e-9 && ...
    max(abs(crossHeaveForce)) < 1e-6 && ...
    max(abs(appliedValues(:, 4))) < 1e-6, ...
    'Incomplete control or nonzero inactive/added heave feedback');
outDir = fullfile(repoRoot, ...
    'matlab-ellipsoid-ode45-continuous-nonlinear-mass-control', waveCase);
if ~isfolder(outDir)
    mkdir(outDir);
end
writematrix(bodyValues, fullfile(outDir, 'body.csv'));
writematrix(appliedValues, fullfile(outDir, 'applied_added.csv'));
writematrix(ptoValues, fullfile(outDir, 'pto.csv'));
writematrix(waveValues, fullfile(outDir, 'wave.csv'));
writematrix([simu.dt, simu.dtOut, simu.nonlinearDt, ...
    simu.cicDt, str2double(get_param(model, 'MaxStep')), 150, ...
    compiledPeriod], fullfile(outDir, 'settings.csv'));
writematrix(massRecord, fullfile(outDir, 'mass.csv'));
close_system(model, 0);
