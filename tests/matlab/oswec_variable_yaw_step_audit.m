function oswec_variable_yaw_step_audit()
% Check whether the pinned irregular selected-bank source is step stable.
% First run the existing 0.01 s, 120 s reference. Reuse its generated
% hydrodynamic bank and change only simu.dt for the second run.
reference_model_baseline('OSWEC_VARIABLE_YAW_IRREGULAR_120S');
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
caseDir = fullfile(repoRoot, 'applications', 'Variable_Hydro', ...
    'paired_Passive_Yaw_irregular_120s');
inputFile = fullfile(caseDir, 'wecSimInputFile.m');
original = fileread(inputFile);
assert(contains(original, 'simu.dt = 0.01;') && ...
    contains(original, 'simu.endTime = 120;') && ...
    contains(original, 'waves.phaseSeed = 1;'), ...
    'The pinned irregular variable-yaw input changed');
contents = strrep(original, 'simu.dt = 0.01;', 'simu.dt = 0.005;');
fid = fopen(inputFile, 'w');
assert(fid ~= -1, 'Could not write the disposable refined input');
fprintf(fid, '%s', contents);
fclose(fid);

outDir = fullfile(repoRoot, 'matlab-oswec-variable-yaw-step-audit');
mkdir(outDir);
cd(caseDir);
waveFlag = 'irregular';
wecSim;
assert(strcmp(simu.solver, 'ode4') && simu.dt == 0.005 && ...
    simu.endTime == 120 && simu.rampTime == 100 && ...
    strcmp(waves.type, 'irregular') && waves.phaseSeed == 1 && ...
    waves.height == 2.5 && waves.period == 8 && ...
    isequal(bemDirections, -30:0.25:30), ...
    'The refined run changed more than the source step');

coarseDir = fullfile(repoRoot, 'matlab-reference-model-output');
prefix = 'OSWEC_VARIABLE_YAW_IRREGULAR_120S';
coarseBody = readmatrix(fullfile(coarseDir, ...
    [prefix '_irregular_120s_body1.csv']));
coarsePto = readmatrix(fullfile(coarseDir, ...
    [prefix '_irregular_120s_pto1.csv']));
coarseHeading = readmatrix(fullfile(coarseDir, ...
    [prefix '_selected_heading.csv']));
coarseWave = readmatrix(fullfile(coarseDir, [prefix '_wave.csv']));
coarseComponents = readmatrix(fullfile(coarseDir, ...
    [prefix '_components.csv']));
fineTime = output.bodies(1).time(:);
fineYaw = output.bodies(1).position(:, 6);
fineRate = output.bodies(1).velocity(:, 6);
fineIndex = output.bodies(1).hydroForceIndex(:);
fineHeading = bemDirections(fineIndex(:));
fineTorque = output.ptos(1).forceInternalMechanics(:, 5);
finePower = output.ptos(1).powerInternalMechanics(:, 5);
fineWave = waves.waveAmpTime;
fineComponents = [waves.omega(:), waves.amplitude(:), ...
    waves.dOmega(:), waves.phase(:)];
assert(numel(fineTime) == 24001 && ...
    isequal(size(fineWave), [24001, 2]) && ...
    isequal(size(coarseBody), [12001, 25]) && ...
    isequal(size(coarsePto), [12001, 25]) && ...
    isequal(size(coarseHeading), [12001, 3]) && ...
    isequal(size(coarseWave), [12001, 2]) && ...
    all(fineIndex >= 1 & fineIndex <= numel(bemDirections)) && ...
    all(isfinite([fineTime, fineYaw, fineRate, fineTorque, ...
        finePower, fineWave]), 'all'), ...
    'The refined source trajectory is incomplete');
assert(max(abs(fineTime(1:2:end) - coarseBody(:, 1))) < 1e-10 && ...
    max(abs(fineWave(1:2:end, :) - coarseWave), [], 'all') < 1e-12 && ...
    max(abs(fineComponents - coarseComponents), [], 'all') < 1e-12, ...
    'Refinement changed the time grid or incident sea');

coarseYaw = coarseBody(:, 7);
coarseRate = coarseBody(:, 13);
coarseTorque = coarsePto(:, 18);
coarsePower = coarsePto(:, 24);
coarseWork = -trapz(coarseBody(:, 1), coarsePower);
fineWork = -trapz(fineTime, finePower);
headingMismatch = coarseHeading(:, 2) ~= fineIndex(1:2:end);
firstMismatch = find(headingMismatch, 1);
metrics = struct( ...
    'maxWaveErrorM', max(abs(fineWave(1:2:end, 2) - coarseWave(:, 2))), ...
    'maxYawErrorRad', max(abs(fineYaw(1:2:end) - coarseYaw)), ...
    'maxYawRateErrorRadPerS', max(abs(fineRate(1:2:end) - coarseRate)), ...
    'maxPtoTorqueErrorNm', max(abs(fineTorque(1:2:end) - coarseTorque)), ...
    'coarsePtoWorkJ', coarseWork, 'finePtoWorkJ', fineWork, ...
    'relativePtoWorkChange', (fineWork - coarseWork) / coarseWork, ...
    'coarseHeadingSwitches', nnz(diff(coarseHeading(:, 2))), ...
    'fineHeadingSwitches', nnz(diff(fineIndex)), ...
    'headingMismatchSamples', nnz(headingMismatch));
if isempty(firstMismatch)
    metrics.firstHeadingMismatchS = -1;
else
    metrics.firstHeadingMismatchS = coarseBody(firstMismatch, 1);
end
fid = fopen(fullfile(outDir, 'metrics.json'), 'w');
assert(fid ~= -1, 'Could not write source step metrics');
fprintf(fid, '%s\n', jsonencode(metrics));
fclose(fid);
writematrix([fineTime, fineYaw, fineRate, fineIndex, ...
    fineHeading(:), fineTorque, finePower], ...
    fullfile(outDir, 'fine_trajectory.csv'));
fprintf('Variable-yaw source step audit: %s\n', jsonencode(metrics));
end
