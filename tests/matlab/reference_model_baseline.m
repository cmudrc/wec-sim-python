        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        for name = ["Float", "Arm", "Frame", "BC", "Motor"]
            oldName = name + ".stl";
            newName = name + ".STL";
            assert(contains(contents, oldName) && ...
                isfile(fullfile(repoRoot, 'applications', 'WECCCOMP', ...
