function export_moving_morison_source(outDir)
% Exercise the pinned moving-element force law at prescribed six-DOF states.
% These are source-function checks, not an integrated WEC trajectory.
t = [0; 1.25; 4; 7; 10; 12; 14; 16];
pose = [0 0 -5 0 0 0; ...
    .2 -.1 -4.5 0 0 0; ...
    .3 .4 -3 .1 -.2 .15; ...
    -.4 .1 -2 .3 .2 -.4; ...
    0 0 -5 0 .2 0; ...
    .1 -.2 -6 -.1 .15 .25; ...
    0 0 .6 0 0 0; ...
    -.4 .3 -3 0 0 .5];
velocity = [.2 -.1 .3 0 0 0; ...
    -.1 .2 -.3 .04 -.02 .01; ...
    .3 -.2 .1 .03 -.04 .02; ...
    -.2 .1 .15 -.05 .01 .04; ...
    .1 .1 -.2 .02 .03 -.01; ...
    -.1 -.2 .3 -.03 .02 .05; ...
    .2 0 0 0 0 0; ...
    .1 -.1 -.15 .04 .03 -.02];
acceleration = [.02 -.01 .04 0 0 0; ...
    -.03 .02 -.01 .005 -.004 .003; ...
    .01 .03 -.02 -.006 .004 .002; ...
    -.02 .01 .04 .003 -.002 -.005; ...
    .03 -.02 .01 -.004 .005 .002; ...
    .01 -.01 -.03 .006 -.003 .004; ...
    0 0 0 0 0 0; ...
    -.02 .03 .01 .002 .001 -.003];
point = [.8 -.5 1.2];
cd = [1.1 .7 1.3];
ca = [.8 1.2 .6];
area = [2 3 1.5];
volume = 1.7;
omega = 2*pi/8;
k = calcWaveNumber(omega, 30, 9.81, 0);
force = zeros(numel(t), 6);
for i = 1:numel(t)
    evaluated = regWaveMorison([0 0 1], point, velocity(i,:), ...
        acceleration(i,:), pose(i,:), area, cd, volume, ca, t(i), ...
        1025, 25, 30, k, omega, 1.25, 10, 9.81, 0, 0, 30, 0, 1);
    force(i,:) = reshape(evaluated, 1, 6);
end
values = [t pose velocity acceleration force];
assert(isequal(size(values), [8 25]) && all(isfinite(values), 'all') ...
    && any(abs(force(:)) > 0), 'Moving Morison source force is invalid');
writematrix(values, fullfile(outDir, 'MORISON_MOVING_REGULAR_states.csv'));
normalTangentialForce = zeros(numel(t), 6);
for i = 1:numel(t)
    evaluated = regWaveMorison([.3 -.7 1.1], point, velocity(i,:), ...
        acceleration(i,:), pose(i,:), area, cd, volume, ca, t(i), ...
        1025, 25, 30, k, omega, 1.25, 10, 9.81, 0, 0, 30, 0, 2);
    normalTangentialForce(i,:) = reshape(evaluated, 1, 6);
end
assert(all(isfinite(normalTangentialForce), 'all') && ...
    any(abs(normalTangentialForce(:) - force(:)) > 1), ...
    'Normal/tangential moving Morison force is invalid');
writematrix([t pose velocity acceleration normalTangentialForce], ...
    fullfile(outDir, 'MORISON_MOVING_NORMAL_TANGENTIAL_states.csv'));
profiles = {'uniform', 'power', 'linear'};
for iProfile = 1:numel(profiles)
    currentForce = zeros(numel(t), 6);
    for i = 1:numel(t)
        evaluated = regWaveMorison([0 0 1], point, velocity(i,:), ...
            acceleration(i,:), pose(i,:), area, cd, volume, ca, t(i), ...
            1025, 25, 30, k, omega, 1.25, 10, 9.81, ...
            .8, 45, 30, iProfile - 1, 1);
        currentForce(i,:) = reshape(evaluated, 1, 6);
    end
    assert(all(isfinite(currentForce), 'all') && ...
        any(abs(currentForce(:) - force(:)) > 1), ...
        'Moving Morison source current force is invalid');
    writematrix([t pose velocity acceleration currentForce], ...
        fullfile(outDir, sprintf( ...
        'MORISON_MOVING_REGULAR_CURRENT_%s_states.csv', profiles{iProfile})));
end
end
