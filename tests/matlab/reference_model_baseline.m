function reference_model_baseline(model)
% Run the published RM3, OSWEC, or Sphere reference cases and save numeric output.
requestedModel = string(model);
selectedContinuousSeed = 0;
if startsWith(requestedModel, "OSWEC_PASSIVE_YAW_IRR_CONT_SEED")
    selectedContinuousSeed = str2double(extractAfter(requestedModel, ...
        "OSWEC_PASSIVE_YAW_IRR_CONT_SEED"));
    assert(ismember(selectedContinuousSeed, [2, 3]), ...
        'Unsupported continuous-yaw phase seed');
    model = "OSWEC_PASSIVE_YAW_IRR_CONT";
end
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
outDir = fullfile(repoRoot, 'matlab-reference-model-output');
if ~isfolder(outDir)
    mkdir(outDir);
end

if any(string(model) == ["RM3_MCR_ARRAY", "RM3_MCR_EXCEL", "RM3_MCR_MAT"])
    run_rm3_mcr_baseline(repoRoot, outDir, string(model));
    return;
end
if string(model) == "RM3_MCR_SEASTATE"
    run_rm3_mcr_seastate_baseline(repoRoot, outDir);
    return;
end

switch string(model)
    case "RM3"
        cases = string(model);
        caseDirs = string(fullfile(repoRoot, 'matlab-ref', 'examples', model));
    case "OSWEC"
        cases = string(model);
        caseDirs = string(fullfile(repoRoot, 'matlab-ref', 'examples', model));
        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        oldSetting = 'waves.spread = [0.1,0.2,0.7];';
        assert(contains(contents, oldSetting), 'The pinned OSWEC input changed');
        contents = strrep(contents, oldSetting, ...
            sprintf('%s\nwaves.phaseSeed = 1;', oldSetting));
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not seed the pinned OSWEC input');
        fprintf(fid, '%s', contents);
        fclose(fid);
    case {"WAVE_MARKERS_RM3", "WAVE_MARKERS_OSWEC"}
        family = extractAfter(string(model), "WAVE_MARKERS_");
        hydroDir = fullfile(repoRoot, 'applications', ...
            '_Common_Input_Files', family, 'hydroData');
        cd(hydroDir);
        if ~isfile(lower(family) + ".h5")
            bemio;
        end
        cases = family;
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Wave_Markers', family));
    case "Sphere"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', 'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = ["0m", "1m", "1m-ME", "3m", "5m"];
        caseDirs = fullfile(repoRoot, 'applications', 'Free_Decay', cases);
    case "SPHERE_ELEVATION_IMPORT"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "0m";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Free_Decay', cases));
        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        oldWave = "waves = waveClass('noWaveCIC');";
        assert(contains(contents, oldWave), ...
            'The pinned Sphere free-decay wave input changed');
        newWave = sprintf(['waves = waveClass(''elevationImport'');\n' ...
            'waves.elevationFile = ''etaData.mat'';\n' ...
            'simu.rampTime = 10;\n' ...
            'simu.solver = ''ode4'';']);
        contents = strrep(contents, char(oldWave), char(newWave));
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not edit the Sphere elevation input');
        fprintf(fid, '%s', contents);
        fclose(fid);
        sampleTime = (0:0.01:40)';
        etaData = [sampleTime, 0.6*cos(2*pi*sampleTime/8) + ...
            0.2*cos(2*pi*sampleTime/3)];
        save(fullfile(caseDirs, 'etaData.mat'), 'etaData');
    case {"SPHERE_MOVING_MORISON", "SPHERE_MOVING_MORISON_WAVE", ...
            "SPHERE_MOVING_MORISON_CURRENT"}
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "1m-ME";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Free_Decay', cases));
        inputFile = fullfile(caseDirs, 'wecSimInputFile.m');
        contents = fileread(inputFile);
        oldSettings = ["morisonElement.cd = [1 0 0];", ...
            "morisonElement.ca = [1 0 0];", ...
            "morisonElement.area = [1 0 0];", ...
            "morisonElement.VME = [0.01];"];
        newSettings = ["morisonElement.cd = [0 0 1];", ...
            "morisonElement.ca = [0 0 1];", ...
            "morisonElement.area = [0 0 100];", ...
            "morisonElement.VME = [20];"];
        for iSetting = 1:numel(oldSettings)
            assert(contains(contents, oldSettings(iSetting)), ...
                'The pinned Sphere Morison input changed');
            contents = strrep(contents, char(oldSettings(iSetting)), ...
                char(newSettings(iSetting)));
        end
        if any(string(model) == ["SPHERE_MOVING_MORISON_WAVE", ...
                                 "SPHERE_MOVING_MORISON_CURRENT"])
            oldWave = "waves = waveClass('noWaveCIC');";
            assert(contains(contents, oldWave), ...
                'The pinned Sphere free-decay wave input changed');
            newWave = sprintf(['waves = waveClass(''regular'');\n' ...
                'waves.height = 1;\nwaves.period = 8;\n' ...
                'simu.rampTime = 10;']);
            contents = strrep(contents, char(oldWave), char(newWave));
        end
        if string(model) == "SPHERE_MOVING_MORISON_CURRENT"
            oldCurrent = 'simu.rampTime = 10;';
            assert(contains(contents, oldCurrent), ...
                'The derived Sphere regular-wave settings changed');
            newCurrent = sprintf([oldCurrent '\n' ...
                'waves.current.option = 1;\n' ...
                'waves.current.speed = 0.8;\n' ...
                'waves.current.direction = 0;\n' ...
                'waves.current.depth = 30;']);
            contents = strrep(contents, oldCurrent, newCurrent);
        end
        fid = fopen(inputFile, 'w');
        assert(fid ~= -1, 'Could not edit the Sphere Morison input');
        fprintf(fid, '%s', contents);
        fclose(fid);
    case "SPHERE_MPC"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "MPC";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Controls', 'MPC'));
    case "SPHERE_REACTIVE_DDPTO"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'Sphere', 'hydroData');
        cd(hydroDir);
        if ~isfile('sphere.h5')
            bemio;
        end
        cases = "ReactiveWithPTO";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Controls', 'ReactiveWithPTO'));
    case "RM3_DD_PTO"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = "RM3_DD_PTO";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'PTO-Sim', 'RM3', 'RM3_DD_PTO'));
    case "RM3_HYDRAULIC_SOURCE"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'RM3', 'hydroData');
        cd(hydroDir);
        if ~isfile('rm3.h5')
            bemio;
        end
        cases = "RM3_cHydraulic_PTO";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'PTO-Sim', 'RM3', cases));
    case "OSWEC_HYDRAULIC_SOURCE"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
