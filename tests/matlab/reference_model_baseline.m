            bemio;
        end
        cases = ["OSWEC_Hydraulic_PTO", "OSWEC_Hydraulic_Crank_PTO"];
        caseDirs = fullfile(repoRoot, 'applications', 'PTO-Sim', ...
            'OSWEC', cases);
    case "OSWEC_DESALINATION_SOURCE"
        hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
            'OSWEC', 'hydroData');
        cd(hydroDir);
        if ~isfile('oswec.h5')
            bemio;
        end
        cases = "Desalination";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Desalination'));
    case "CABLE_SOURCE"
        hydroDir = fullfile(repoRoot, 'applications', 'Cable', 'hydroData');
        cd(hydroDir);
        if ~isfile('mbari.h5')
            bemio;
        end
        cases = "Cable";
        caseDirs = string(fullfile(repoRoot, 'applications', 'Cable'));
    case "WAVEBOT_IMPEDANCE"
        hydroDir = fullfile(repoRoot, 'applications', ...
            'Load_Mitigating_Controls', 'hydroData');
        cd(hydroDir);
        if ~isfile('waveBotBuoy.h5')
            bemio;
        end
        cases = "CalcImpedance";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Load_Mitigating_Controls', cases));
    case "WAVEBOT_CONTROL"
        hydroDir = fullfile(repoRoot, 'applications', ...
            'Load_Mitigating_Controls', 'hydroData');
        cd(hydroDir);
        if ~isfile('waveBotBuoy.h5')
            bemio;
        end
        cases = "ControlTests";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
            'Load_Mitigating_Controls', cases));
    case "WECCCOMP_SOURCE"
        hydroDir = fullfile(repoRoot, 'applications', 'WECCCOMP', 'hydroData');
        cd(hydroDir);
        if ~isfile('wavestar.h5')
            bemio;
        end
        cases = "WECCCOMP";
        caseDirs = string(fullfile(repoRoot, 'applications', ...
