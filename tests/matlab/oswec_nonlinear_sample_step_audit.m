function oswec_nonlinear_sample_step_audit
% Isolate nonlinear-force sampling from the ode4 solver step in the 120 s case.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
    'OSWEC', 'hydroData');
cd(hydroDir);
if ~isfile('oswec.h5')
    bemio;
end
caseDir = fullfile(repoRoot, 'applications', 'Paraview_Visualization', ...
    'OSWEC_NonLinear_Viz');
inputFile = fullfile(caseDir, 'wecSimInputFile.m');
original = fileread(inputFile);
assert(contains(original, 'simu.dt = 0.1;') && ...
    contains(original, 'simu.pressure = 1;') && ...
    contains(original, 'simu.paraview.option = 1;') && ...
    ~contains(original, 'simu.nonlinearDt'), ...
    'Pinned nonlinear OSWEC input changed');
restoreInput = onCleanup(@() writeInput(inputFile, original));
outDir = fullfile(repoRoot, 'matlab-oswec-nonlinear-sample-step');
mkdir(outDir);

% Both arms use the same 0.0125 s solver/output/radiation grids. Only the
% nonlinear-pressure sample interval changes to the published 0.1 s value.
runArm(caseDir, inputFile, original, outDir, 0.0125, 'fine');
runArm(caseDir, inputFile, original, outDir, 0.1, 'coarse-force');
end

function runArm(caseDir, inputFile, original, outDir, nonlinearDt, label)
contents = strrep(original, 'simu.dt = 0.1;', ...
    sprintf('simu.dt = 0.0125;\nsimu.nonlinearDt = %.6g;', nonlinearDt));
contents = strrep(contents, 'simu.pressure = 1;', ...
    'simu.pressure = 0;');
contents = strrep(contents, 'simu.paraview.option = 1;', ...
    'simu.paraview.option = 0;');
writeInput(inputFile, contents);
cd(caseDir);
wecSim;
assert(simu.dt == 0.0125 && simu.nonlinearDt == nonlinearDt && ...
    simu.dtOut == 0.0125 && simu.cicDt == 0.0125 && ...
    simu.endTime == 120 && simu.rampTime == 40 && ...
    simu.pressure == 0 && simu.paraview.option == 0 && ...
    strcmp(simu.solver, 'ode4') && ...
    strcmp(waves.type, 'regular') && waves.height == 2.5 && ...
    waves.period == 8 && body(1).nonlinearHydro == 2 && ...
    body(1).mass == 127000 && pto(1).damping == 0 && ...
    pto(1).stiffness == 0, ...
    'Sample-step audit changed an unintended source setting');
time = output.bodies(1).time;
pose = output.bodies(1).position;
velocity = output.bodies(1).velocity;
acceleration = output.bodies(1).acceleration;
forceExcitation = output.bodies(1).forceExcitation;
forceRadiationDamping = output.bodies(1).forceRadiationDamping;
forceAddedMass = output.bodies(1).forceAddedMass;
forceRestoring = output.bodies(1).forceRestoring;
assert(numel(time) == 9601 && ...
    all(isfinite([pose, velocity, acceleration, forceExcitation, ...
        forceRadiationDamping, forceAddedMass, forceRestoring]), 'all'), ...
    'Sample-step audit has missing or nonfinite source samples');
save(fullfile(outDir, [label '.mat']), 'time', 'pose', 'velocity', ...
    'acceleration', 'forceExcitation', 'forceRadiationDamping', ...
    'forceAddedMass', 'forceRestoring', 'nonlinearDt', '-v7');
end

function writeInput(path, contents)
fid = fopen(path, 'w');
assert(fid ~= -1, 'Could not write disposable OSWEC input');
fprintf(fid, '%s', contents);
fclose(fid);
end
