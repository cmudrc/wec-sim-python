function wavestar_ode8_stage_forcing_probe(coreDir, inputMat, outputCsv)
% Evaluate the pinned irregExcF directly at off-grid ode8 stage times.
addpath(fullfile(coreDir, 'source', 'functions', 'simulink', 'model'));
source = load(inputMat);
assert(isequal(size(source.re), [1, 500, 6]) && ...
    isequal(size(source.im), [1, 500, 6]) && ...
    isequal(size(source.md), [1, 500, 6]) && ...
    isequal(size(source.phase), [500, 1]) && ...
    numel(source.times) == 5, 'Unexpected WaveStar stage inputs');
force = zeros(numel(source.times), 6);
for index = 1:numel(source.times)
    force(index, :) = irregExcF(source.A, source.w, source.re, ...
        source.im, source.phase, source.dw, source.times(index), ...
        source.direction, source.spread, source.md);
end
writematrix([source.times(:), force], outputCsv);
end
