function oswec_passive_yaw_continuous_step_refinement(phaseSeed, steps)
% Check whether disabling the published 1-degree coefficient hold stabilizes
% the same three 250 s seas. The pinned application input is never edited.
if nargin < 2
    steps = [0.01, 0.005];
end
assert(ismember(phaseSeed, [1, 2, 3]) && ...
    all(ismember(steps, [0.01, 0.005])) && numel(unique(steps)) == numel(steps), ...
    'Unexpected phase seed or time steps');
originalFolder = pwd;
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
    'OSWEC', 'hydroData');
cd(hydroDir);
if ~isfile('oswec.h5')
    bemio;
end
sourceDir = fullfile(repoRoot, 'applications', 'Passive_Yaw', ...
    'PassiveYawRegression');
original = fileread(fullfile(sourceDir, 'wecSimInputFile.m'));
assert(contains(original, 'simu.dt = 0.01;') && ...
    contains(original, 'simu.endTime = 250;') && ...
    contains(original, 'waves.phaseSeed = 1;') && ...
    contains(original, 'body(1).yaw.threshold = 1;') && ...
    contains(original, 'body(2).yaw.threshold = 1;'), ...
    'Pinned passive-yaw input changed');
caseDir = fullfile(repoRoot, 'applications', 'Passive_Yaw', ...
    sprintf('PassiveYawContinuousStepSeed%d', phaseSeed));
assert(~isfolder(caseDir), 'Disposable continuous-yaw case already exists');
mkdir(caseDir);
cleanup = onCleanup(@() cleanupCase(caseDir, originalFolder));
copyfile(fullfile(sourceDir, 'OSWEC.slx'), fullfile(caseDir, 'OSWEC.slx'));
inputFile = fullfile(caseDir, 'wecSimInputFile.m');
outDir = fullfile(repoRoot, 'matlab-oswec-passive-yaw-continuous-refinement');
mkdir(outDir);
for dt = steps
    contents = strrep(original, 'simu.dt = 0.01;', ...
        sprintf('simu.dt = %.6g;', dt));
    contents = strrep(contents, 'waves.phaseSeed = 1;', ...
        sprintf('waves.phaseSeed = %d;', phaseSeed));
    for iBody = 1:2
        contents = strrep(contents, ...
            sprintf('body(%d).yaw.threshold = 1;', iBody), ...
            sprintf('body(%d).yaw.threshold = 0;', iBody));
    end
    fid = fopen(inputFile, 'w');
    assert(fid ~= -1, 'Could not write disposable continuous-yaw input');
    fprintf(fid, '%s', contents);
    fclose(fid);
    cd(caseDir);
    wecSim;
    assert(simu.dt == dt && simu.endTime == 250 && ...
        simu.rampTime == 100 && strcmp(simu.solver, 'ode4') && ...
        strcmp(waves.type, 'irregular') && waves.phaseSeed == phaseSeed && ...
        waves.height == 2.5 && waves.period == 8 && ...
        body(1).yaw.threshold == 0 && body(2).yaw.threshold == 0, ...
        'Continuous-yaw refinement changed another setting');
    time = output.bodies(1).time;
    yaw = output.bodies(1).position(:, 6);
    yawRate = output.bodies(1).velocity(:, 6);
    ptoPower = output.ptos(1).powerInternalMechanics(:, 5);
    ptoForce = output.ptos(1).forceInternalMechanics(:, 5);
    wave = waves.waveAmpTime;
    work = -trapz(time, ptoPower);
    assert(numel(time) == round(250 / dt) + 1 && ...
        isequal(size(wave), [numel(time), 2]) && ...
        all(isfinite([time, yaw, yawRate, ptoPower, ptoForce, wave]), 'all') && ...
        isfinite(work) && work > 0, ...
        'Continuous-yaw refinement has missing or nonfinite output');
    save(fullfile(outDir, sprintf('seed-%d-dt-%g.mat', phaseSeed, dt)), ...
        'phaseSeed', 'dt', 'time', 'yaw', 'yawRate', ...
        'ptoPower', 'ptoForce', 'wave', 'work', '-v7');
end
if numel(steps) == 2
    coarse = load(fullfile(outDir, sprintf('seed-%d-dt-0.01.mat', phaseSeed)));
    fine = load(fullfile(outDir, sprintf('seed-%d-dt-0.005.mat', phaseSeed)));
    assert(max(abs(coarse.time - fine.time(1:2:end))) < 1e-10 && ...
        max(abs(coarse.wave(:, 2) - fine.wave(1:2:end, 2))) < 1e-11, ...
        'Continuous-yaw runs did not see the same wave');
    fprintf('Seed %d continuous-yaw: yaw %.6g rad, speed %.6g rad/s, torque %.6g N m, work %.6g%%\n', ...
        phaseSeed, max(abs(coarse.yaw - fine.yaw(1:2:end))), ...
        max(abs(coarse.yawRate - fine.yawRate(1:2:end))), ...
        max(abs(coarse.ptoForce - fine.ptoForce(1:2:end))), ...
        100 * (fine.work / coarse.work - 1));
end
end

function cleanupCase(caseDir, originalFolder)
if bdIsLoaded('OSWEC')
    close_system('OSWEC', 0);
end
cd(originalFolder);
if isfolder(caseDir)
    rmdir(caseDir, 's');
end
end
