function sphere_mpc_independent_qp_probe(applicationsDir, setupFile, inputFile, outputFile)
% Evaluate the pinned mpcFcn on states and forecasts from Python's own run.
% No MATLAB body or controller state is supplied to this direct QP check.
assert(~isempty(which('quadprog')), 'quadprog is required');
addpath(fullfile(applicationsDir, 'Controls', 'MPC'));
inputs = load(inputFile);
saved = load(setupFile);
setup = saved.setup;
assert(isequal(size(inputs.states), [9, 391]) && ...
       isequal(size(inputs.forecasts), [31, 391]) && ...
       numel(inputs.times) == 391, 'Python QP inputs are incomplete');

matlab_commands = zeros(1, 391);
failures = zeros(1, 391);
for index = 1:391
    % The published MPC is active once currentIteration > Ho + order.
    [matlab_commands(index), ~, failures(index)] = mpcFcn( ...
        inputs.states(:, index), inputs.forecasts(:, index), ...
        setup.Sx, setup.Su, setup.Sv, setup.Q, setup.HpInk, ...
        setup.H, 3, 3, 4, 2e6, 1.5e6, 200, 4, setup.outputSize, ...
        205, inputs.times(index), 0);
end
assert(all(isfinite(matlab_commands)) && all(failures == 0), ...
       'Published mpcFcn returned an infeasible or nonfinite command');
save(outputFile, 'matlab_commands', 'failures', '-v7');
fprintf('SPHERE_MPC_INDEPENDENT_QP max=%0.12g rms=%0.12g count=%d\n', ...
    max(abs(matlab_commands - inputs.python_commands)), ...
    sqrt(mean((matlab_commands - inputs.python_commands).^2)), ...
    numel(matlab_commands));
end
