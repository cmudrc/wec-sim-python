function oswec_nonlinear_viz_corrected_baseline
% Run a repository-owned corrected visualization case from disposable copies.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
    'OSWEC', 'hydroData');
cd(hydroDir);
if ~isfile('oswec.h5')
    bemio;
end
sourceDir = fullfile(repoRoot, 'applications', 'Paraview_Visualization', ...
    'OSWEC_NonLinear_Viz');
original = fileread(fullfile(sourceDir, 'wecSimInputFile.m'));
assert(contains(original, 'simu.dt = 0.1;') && ...
    contains(original, 'simu.pressure = 1;') && ...
    contains(original, 'simu.paraview.option = 1;') && ...
    ~contains(original, 'simu.dtOut'), ...
    'Pinned published OSWEC input changed');
outDir = fullfile(repoRoot, 'matlab-oswec-nonlinear-viz-corrected');
mkdir(outDir);

% Keep the published 0.1 s output/visualization grid while refining the
% solver, radiation, and nonlinear-force clocks together. The second arm
% changes only dt again and checks stability; pressure/VTP logging is
% disabled there because the first arm owns the complete output history.
runArm(repoRoot, sourceDir, original, outDir, 0.0125, true);
runArm(repoRoot, sourceDir, original, outDir, 0.00625, false);
end

function runArm(repoRoot, sourceDir, original, outDir, dt, logScene)
caseDir = fullfile(repoRoot, 'applications', 'Paraview_Visualization', ...
    sprintf('OSWEC_NonLinear_Viz_corrected_%g', dt));
mkdir(caseDir);
assert(copyfile(fullfile(sourceDir, 'OSWEC.slx'), ...
    fullfile(caseDir, 'OSWEC.slx')), 'Could not copy OSWEC model');
contents = strrep(original, 'simu.dt = 0.1;', ...
    sprintf('simu.dt = %.6g;\nsimu.dtOut = 0.1;', dt));
if ~logScene
    contents = strrep(contents, 'simu.pressure = 1;', ...
        'simu.pressure = 0;');
    contents = strrep(contents, 'simu.paraview.option = 1;', ...
        'simu.paraview.option = 0;');
end
fid = fopen(fullfile(caseDir, 'wecSimInputFile.m'), 'w');
assert(fid ~= -1, 'Could not create disposable OSWEC input');
fprintf(fid, '%s', contents);
fclose(fid);
cd(caseDir);
wecSim;
assert(simu.dt == dt && simu.dtOut == 0.1 && ...
    simu.nonlinearDt == dt && simu.cicDt == dt && ...
    simu.endTime == 120 && simu.rampTime == 40 && ...
    simu.pressure == logScene && simu.paraview.option == logScene && ...
    strcmp(simu.solver, 'ode4') && ...
    strcmp(waves.type, 'regular') && waves.height == 2.5 && ...
    waves.period == 8 && body(1).nonlinearHydro == 2 && ...
    body(1).mass == 127000 && pto(1).damping == 0 && ...
    pto(1).stiffness == 0, ...
    'Corrected run changed more than the numerical grid or output logging');
assert(numel(output.bodies(1).time) == 1201 && ...
    numel(output.ptos(1).time) == 1201 && ...
    all(isfinite([output.bodies(1).position, ...
        output.bodies(1).velocity]), 'all'), ...
    'Corrected OSWEC output is incomplete');
time = output.bodies(1).time;
pose = output.bodies(1).position;
velocity = output.bodies(1).velocity;
basePose = output.bodies(2).position;
baseVelocity = output.bodies(2).velocity;
ptoTime = output.ptos(1).time;
ptoPosition = output.ptos(1).position;
ptoVelocity = output.ptos(1).velocity;
ptoForce = output.ptos(1).forceInternalMechanics;
ptoPower = output.ptos(1).powerInternalMechanics;
if logScene
    assert(simu.paraview.dt == 0.1 && ...
        numel(output.bodies(1).cellPressures_time) == 1201, ...
        'Corrected pressure or ParaView grid changed');
    pressureTime = output.bodies(1).cellPressures_time;
    hydrostatic = output.bodies(1).cellPressures_hydrostatic;
    nonlinearWave = output.bodies(1).cellPressures_waveNonLinear;
    linearWave = output.bodies(1).cellPressures_waveLinear;
    waveNumber = waves.wavenumber;
    waterDepth = waves.waterDepth;
    areas = body(1).geometry.area;
    assert(isequal(size(hydrostatic), [1201, 1042]) && ...
        isequal(size(nonlinearWave), [1201, 1042]) && ...
        isequal(size(linearWave), [1201, 1042]) && ...
        all(isfinite([hydrostatic, nonlinearWave, linearWave]), 'all'), ...
        'Corrected source facet pressures are incomplete');
    save(fullfile(outDir, 'baseline.mat'), 'dt', 'time', 'pose', ...
        'velocity', 'basePose', 'baseVelocity', 'ptoTime', ...
        'ptoPosition', 'ptoVelocity', 'ptoForce', 'ptoPower', ...
        'pressureTime', 'hydrostatic', 'nonlinearWave', 'linearWave', ...
        'waveNumber', 'waterDepth', 'areas', '-v7');
    vtkDir = fullfile(caseDir, simu.paraview.path);
    sampleDir = fullfile(outDir, 'vtp_samples');
    mkdir(sampleDir);
    for file = {'ground.txt', 'bodies.txt', 'OSWEC.pvd'}
        assert(copyfile(fullfile(vtkDir, file{1}), sampleDir), ...
            'Missing corrected scene metadata');
    end
    for frame = [1, 601, 1201]
        for folder = {'waves', 'body1_flap', 'body2_base'}
            name = folder{1};
            mkdir(fullfile(sampleDir, name));
            if strcmp(name, 'waves')
                filename = sprintf('waves_%d.vtp', frame);
            elseif strcmp(name, 'body1_flap')
                filename = sprintf('flap_%d.vtp', frame);
            else
                filename = sprintf('base_%d.vtp', frame);
            end
            assert(copyfile(fullfile(vtkDir, name, filename), ...
                fullfile(sampleDir, name, filename)), ...
                'Missing corrected VTP sample');
        end
    end
else
    save(fullfile(outDir, 'stability.mat'), 'dt', 'time', 'pose', ...
        'velocity', 'basePose', 'baseVelocity', 'ptoTime', ...
        'ptoPosition', 'ptoVelocity', 'ptoForce', 'ptoPower', '-v7');
end
close_system('OSWEC', 0);
end
