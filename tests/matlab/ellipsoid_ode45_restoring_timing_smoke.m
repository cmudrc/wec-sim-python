% Isolate the nonlinear restoring calculation's sample time in the pinned
% ellipsoid ode45 model. Invoke with waveCase, mode, optional duration, and
% optional maxStep (0.05 by default; 0.025 and 0.0125 for the predeclared
% screen; 0.00625 and 0.003125 for post-screen diagnosis).
% mode: baseline, continuous_restoring, or continuous_nonlinear.
% duration: smoke (2 s, default) or full (150 s).
assert(any(strcmp(waveCase, {'Regular', 'RegularCIC'})));
assert(any(strcmp(mode, {'baseline', 'continuous_restoring', ...
    'continuous_nonlinear'})));
if ~exist('duration', 'var')
    duration = 'smoke';
end
assert(any(strcmp(duration, {'smoke', 'full'})));
if ~exist('maxStep', 'var')
    maxStep = .05;
end
assert(isnumeric(maxStep) && isscalar(maxStep) && isfinite(maxStep) && ...
    any(abs(maxStep - [.05, .025, .0125, .00625, .003125]) < 1e-12), ...
    'MaxStep must be a supported copied-model value');
if abs(maxStep - .05) >= 1e-12
    assert(strcmp(mode, 'continuous_nonlinear') && ...
        strcmp(duration, 'full'), ...
        'The source-step screen is only the 150 s continuous nonlinear arm');
end
stepTag = strrep(num2str(maxStep, '%.4g'), '.', 'p');
stopTime = 2;
if strcmp(duration, 'full')
    stopTime = 150;
end

repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
sourceDir = fullfile(repoRoot, 'matlab-ref', 'source');
appDir = fullfile(repoRoot, 'applications', 'Nonlinear_Hydro');
hydroDir = fullfile(appDir, 'hydroData');
originalDir = fullfile(appDir, 'ode45', waveCase);
addpath(genpath(sourceDir));
cd(hydroDir);
if ~isfile('ellipsoid.h5')
    bemio;
end

original = fileread(fullfile(originalDir, 'wecSimInputFile.m'));
assert(contains(original, 'simu.solver=''ode45'';') && ...
    contains(original, 'simu.dt = 0.05;') && ...
    contains(original, 'simu.endTime=150;') && ...
    contains(original, 'body(1).nonlinearHydro = 2;') && ...
    ~contains(original, 'simu.dtOut') && ...
    ~contains(original, 'simu.nonlinearDt') && ...
    ~contains(original, 'simu.cicDt') && ...
    ~contains(original, 'body(1).adjMassFactor'), ...
    'The pinned published input has changed');
caseName = [waveCase '_restoring_timing_' mode '_' duration];
if abs(maxStep - .05) >= 1e-12
    caseName = [caseName '_maxstep_' stepTag];
end
caseDir = fullfile(fileparts(originalDir), caseName);
assert(~isfolder(caseDir), 'Disposable timing case already exists');
mkdir(caseDir);
copyfile(fullfile(originalDir, 'ellipsoid.slx'), ...
    fullfile(caseDir, 'ellipsoid.slx'));
copyfile(fullfile(originalDir, 'wecSimInputFile.m'), ...
    fullfile(caseDir, 'wecSimInputFile.m'));
assert(strcmp(fileread(fullfile(caseDir, 'wecSimInputFile.m')), original));

cd(caseDir);
run('initializeWecSim');
assert(strcmp(simu.solver, 'ode45') && ...
    abs(simu.dt - .05) < 1e-12 && ...
    abs(simu.dtOut - .05) < 1e-12 && ...
    abs(simu.nonlinearDt - .05) < 1e-12 && ...
    abs(simu.cicDt - .05) < 1e-12 && ...
    simu.endTime == 150 && simu.rampTime == 50, ...
    'A published physical or output clock changed');
model = 'ellipsoid';
assert(abs(str2double(get_param(model, 'MaxStep')) - .05) < 1e-12);
delayBlock = [model '/Rigid Body/Hydrodynamic Body/Transport Delay'];
assert(abs(str2double(get_param(delayBlock, 'DelayTime')) - 1e-7) < 1e-16);

% All arms detach the same copied library link. The source-step screen
% changes only copied-model MaxStep beyond the continuous nonlinear arm.
bodyLink = [model '/Rigid Body'];
if ~strcmp(get_param(bodyLink, 'LinkStatus'), 'none')
    set_param(bodyLink, 'LinkStatus', 'none');
end
hydroLink = [bodyLink '/Hydrodynamic Body'];
if ~strcmp(get_param(hydroLink, 'LinkStatus'), 'none')
    set_param(hydroLink, 'LinkStatus', 'none');
end
restoringBlock = [hydroLink ...
    '/Hydrostatic Restoring Force Calculation' ...
    '/Linear and Nonlinear Restoring Force Variant Subsystem' ...
    '/Nonlinear Hydrostatic Restoring Force/Restoring Forces'];
fkBlock = [hydroLink ...
    '/Wave Diffraction and Excitation Force Calculation' ...
    '/Nonlinear FK Force Variant Subsystem' ...
    '/With Nonlinear FroudeKrylov Force'];
waveBlock = [hydroLink '/Nonlinear Wave Elevation'];
blocks = {restoringBlock, fkBlock, waveBlock};
for iBlock = 1:numel(blocks)
    assert(strcmp(get_param(blocks{iBlock}, 'TreatAsAtomicUnit'), 'on') && ...
        strcmp(get_param(blocks{iBlock}, 'SystemSampleTime'), ...
               'simu.nonlinearDt'), ...
        'A pinned nonlinear sample-time block changed');
end
if ~strcmp(mode, 'baseline')
    set_param(restoringBlock, 'SystemSampleTime', '0');
end
if strcmp(mode, 'continuous_nonlinear')
    set_param(fkBlock, 'SystemSampleTime', '0');
    set_param(waveBlock, 'SystemSampleTime', '0');
end
expectedPeriod = [.05, .05, .05];
if ~strcmp(mode, 'baseline')
    expectedPeriod(1) = 0;
end
if strcmp(mode, 'continuous_nonlinear')
    expectedPeriod(2:3) = 0;
end
for iBlock = 1:numel(blocks)
    param = get_param(blocks{iBlock}, 'SystemSampleTime');
    if expectedPeriod(iBlock) == 0
        assert(strcmp(param, '0'), 'Continuous block change did not persist');
    else
        assert(strcmp(param, 'simu.nonlinearDt'), ...
            'A non-target nonlinear block clock changed');
    end
end

if abs(maxStep - .05) >= 1e-12
    set_param(model, 'MaxStep', num2str(maxStep, '%.17g'));
end
set_param(model, 'StopTime', num2str(stopTime));
set_param(model, 'SimulationCommand', 'update');
compiledPeriod = zeros(1, numel(blocks));
for iBlock = 1:numel(blocks)
    sample = get_param(blocks{iBlock}, 'CompiledSampleTime');
    fprintf('COMPILED_SAMPLE_TIMES case=%s mode=%s block=%d\n', ...
        waveCase, mode, iBlock);
    disp(sample);
    if ~iscell(sample)
        sample = {sample};
    end
    rates = zeros(1, numel(sample));
    for iRate = 1:numel(sample)
        pair = sample{iRate};
        if ischar(pair) || isstring(pair)
            pair = str2num(char(pair)); %#ok<ST2NM> compiled Simulink value
        end
        assert(isnumeric(pair) && numel(pair) == 2 && ...
            abs(pair(2)) < 1e-12, ...
            'Nonlinear block has an unparseable compiled sample time');
        rates(iRate) = pair(1);
    end
    assert(any(abs(rates - expectedPeriod(iBlock)) < 1e-12), ...
        'Expected nonlinear sample period is absent from compiled rates');
    compiledPeriod(iBlock) = expectedPeriod(iBlock);
end
assert(abs(str2double(get_param(model, 'MaxStep')) - maxStep) < 1e-12 && ...
    abs(str2double(get_param(delayBlock, 'DelayTime')) - 1e-7) < 1e-16 && ...
    abs(str2double(get_param(model, 'StopTime')) - stopTime) < 1e-12, ...
    'The model solver, feedback delay, or duration changed');
fprintf(['RESTORING_TIMING case=%s mode=%s duration=%s dt=%.9g ' ...
    'dtOut=%.9g nonlinearDt=%.9g cicDt=%.9g MaxStep=%.9g ' ...
    'compiledRestoring=%.9g compiledFK=%.9g compiledWave=%.9g\n'], ...
    waveCase, mode, duration, simu.dt, simu.dtOut, simu.nonlinearDt, ...
    simu.cicDt, str2double(get_param(model, 'MaxStep')), compiledPeriod);

sim(simu.simMechanicsFile, [], simset('SrcWorkspace', 'parent'));
assert(abs(str2double(get_param(model, 'MaxStep')) - maxStep) < 1e-12 && ...
    abs(str2double(get_param(model, 'StopTime')) - stopTime) < 1e-12, ...
    'Simulink changed the prescribed source-step screen settings');
if abs(maxStep - .05) < 1e-12
    outDir = fullfile(repoRoot, ...
        'matlab-ellipsoid-ode45-restoring-timing', waveCase);
else
    outDir = fullfile(repoRoot, ...
        'matlab-ellipsoid-ode45-restoring-timing-step', waveCase, ...
        ['maxstep_' stepTag]);
end
if ~isfolder(outDir)
    mkdir(outDir);
end
run('stopWecSim');
record = output.bodies(1);
bodyValues = [record.time(:), record.position, record.velocity, ...
    record.forceTotal, record.forceExcitation, ...
    record.forceRadiationDamping, record.forceAddedMass, ...
    record.forceRestoring, record.forceMorisonAndViscous, ...
    record.acceleration];
pto = output.ptos(1);
ptoValues = [pto.time(:), pto.position, pto.velocity, ...
    pto.forceInternalMechanics, pto.powerInternalMechanics];
waveValues = [output.wave.time(:), output.wave.elevation(:)];
expectedRows = round(stopTime / .05) + 1;
assert(isequal(size(bodyValues), [expectedRows, 55]) && ...
    isequal(size(ptoValues), [expectedRows, 25]) && ...
    isequal(size(waveValues), [expectedRows, 2]) && ...
    max(abs(bodyValues(:, 1) - (0:expectedRows-1)' * .05)) < 1e-9 && ...
    max(abs(ptoValues(:, 1) - bodyValues(:, 1))) < 1e-9 && ...
    max(abs(waveValues(:, 1) - bodyValues(:, 1))) < 1e-9 && ...
    all(isfinite(bodyValues), 'all') && ...
    all(isfinite(ptoValues), 'all') && ...
    all(isfinite(waveValues), 'all'), ...
    'Incomplete published-grid source output');
writematrix(bodyValues, fullfile(outDir, [mode '_body.csv']));
writematrix(ptoValues, fullfile(outDir, [mode '_pto.csv']));
writematrix(waveValues, fullfile(outDir, [mode '_wave.csv']));
writematrix([simu.dt, simu.dtOut, simu.nonlinearDt, ...
    simu.cicDt, str2double(get_param(model, 'MaxStep')), ...
    stopTime, compiledPeriod], ...
    fullfile(outDir, [mode '_settings.csv']));
close_system(model, 0);
