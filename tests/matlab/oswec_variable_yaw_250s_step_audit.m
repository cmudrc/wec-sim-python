function oswec_variable_yaw_250s_step_audit()
% Extend the pinned irregular selected-bank step comparison through the
% first material full-duration trajectory separation. Do not infer parity
% from this source-only audit.
reference_model_baseline('OSWEC_VARIABLE_YAW_IRREGULAR_120S');
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
caseDir = fullfile(repoRoot, 'applications', 'Variable_Hydro', ...
    'paired_Passive_Yaw_irregular_120s');
inputFile = fullfile(caseDir, 'wecSimInputFile.m');
original = fileread(inputFile);
assert(contains(original, 'simu.dt = 0.01;') && ...
    contains(original, 'simu.endTime = 120;') && ...
    contains(original, 'waves.phaseSeed = 1;'), ...
    'The pinned irregular variable-yaw input changed');
outDir = fullfile(repoRoot, 'matlab-oswec-variable-yaw-250s-audit');
mkdir(outDir);
cd(caseDir);

write_input(strrep(original, 'simu.endTime = 120;', ...
    'simu.endTime = 250;'));
waveFlag = 'irregular';
wecSim;
check_run(0.01, 25001);
coarse = trajectory();
coarseWave = waves.waveAmpTime;
coarseComponents = [waves.omega(:), waves.amplitude(:), ...
    waves.dOmega(:), waves.phase(:)];
baselineDir = fullfile(repoRoot, 'matlab-reference-model-output');
prefix = 'OSWEC_VARIABLE_YAW_IRREGULAR_120S';
baselineBody = readmatrix(fullfile(baselineDir, ...
    [prefix '_irregular_120s_body1.csv']));
baselinePto = readmatrix(fullfile(baselineDir, ...
    [prefix '_irregular_120s_pto1.csv']));
baselineHeading = readmatrix(fullfile(baselineDir, ...
    [prefix '_selected_heading.csv']));
baselineWave = readmatrix(fullfile(baselineDir, [prefix '_wave.csv']));
assert(isequal(size(baselineBody), [12001, 25]) && ...
    isequal(size(baselinePto), [12001, 25]) && ...
    isequal(size(baselineHeading), [12001, 3]) && ...
    max(abs(coarse(1:12001, 2) - baselineBody(:, 7))) < 1e-10 && ...
    max(abs(coarse(1:12001, 3) - baselineBody(:, 13))) < 1e-10 && ...
    max(abs(coarse(1:12001, 6) - baselinePto(:, 18))) < 1e-6 && ...
    isequal(coarse(1:12001, 4), baselineHeading(:, 2)) && ...
    max(abs(coarseWave(1:12001, :) - baselineWave), [], 'all') < 1e-12, ...
    'Changing only end time altered the existing source baseline');
writematrix(coarse, fullfile(outDir, 'coarse_trajectory.csv'));
writematrix(coarseWave, fullfile(outDir, 'coarse_wave.csv'));
writematrix(coarseComponents, fullfile(outDir, 'components.csv'));

write_input(strrep(fileread(inputFile), 'simu.dt = 0.01;', ...
    'simu.dt = 0.005;'));
wecSim;
check_run(0.005, 50001);
fine = trajectory();
fineWave = waves.waveAmpTime;
fineComponents = [waves.omega(:), waves.amplitude(:), ...
    waves.dOmega(:), waves.phase(:)];
assert(max(abs(fine(1:2:end, 1) - coarse(:, 1))) < 1e-10 && ...
    max(abs(fineWave(1:2:end, :) - coarseWave), [], 'all') < 1e-12 && ...
    max(abs(fineComponents - coarseComponents), [], 'all') < 1e-12, ...
    'Source refinement changed the time grid or incident sea');
writematrix(fine, fullfile(outDir, 'fine_trajectory.csv'));
writematrix(fineWave, fullfile(outDir, 'fine_wave.csv'));

coarseWork = -trapz(coarse(:, 1), coarse(:, 7));
fineWork = -trapz(fine(:, 1), fine(:, 7));
mismatch = coarse(:, 4) ~= fine(1:2:end, 4);
firstMismatch = find(mismatch, 1);
metrics = struct( ...
    'maxWaveErrorM', max(abs(fineWave(1:2:end, 2) - coarseWave(:, 2))), ...
    'maxYawErrorRad', max(abs(fine(1:2:end, 2) - coarse(:, 2))), ...
    'maxYawRateErrorRadPerS', max(abs(fine(1:2:end, 3) - coarse(:, 3))), ...
    'maxPtoTorqueErrorNm', max(abs(fine(1:2:end, 6) - coarse(:, 6))), ...
    'coarsePtoWorkJ', coarseWork, 'finePtoWorkJ', fineWork, ...
    'relativePtoWorkChange', (fineWork - coarseWork) / coarseWork, ...
    'coarseHeadingSwitches', nnz(diff(coarse(:, 4))), ...
    'fineHeadingSwitches', nnz(diff(fine(:, 4))), ...
    'headingMismatchSamples', nnz(mismatch));
if isempty(firstMismatch)
    metrics.firstHeadingMismatchS = -1;
else
    metrics.firstHeadingMismatchS = coarse(firstMismatch, 1);
end
fid = fopen(fullfile(outDir, 'metrics.json'), 'w');
assert(fid ~= -1, 'Could not write source step metrics');
fprintf(fid, '%s\n', jsonencode(metrics));
fclose(fid);
fprintf('Variable-yaw 250 s source step audit: %s\n', jsonencode(metrics));

    function write_input(contents)
        fidInput = fopen(inputFile, 'w');
        assert(fidInput ~= -1, 'Could not write the disposable input');
        fprintf(fidInput, '%s', contents);
        fclose(fidInput);
    end

    function check_run(expectedDt, expectedSamples)
        assert(strcmp(simu.solver, 'ode4') && simu.dt == expectedDt && ...
            simu.endTime == 250 && simu.rampTime == 100 && ...
            strcmp(waves.type, 'irregular') && waves.phaseSeed == 1 && ...
            waves.height == 2.5 && waves.period == 8 && ...
            isequal(bemDirections, -30:0.25:30), ...
            'The extended run changed more than time or step');
        assert(numel(output.bodies(1).time) == expectedSamples && ...
            isequal(size(waves.waveAmpTime), [expectedSamples, 2]) && ...
            all(isfinite(waves.waveAmpTime), 'all'), ...
            'The extended source run is incomplete');
    end

    function values = trajectory()
        index = output.bodies(1).hydroForceIndex(:);
        assert(all(index >= 1 & index <= numel(bemDirections)), ...
            'Selected heading index is outside the generated bank');
        selectedHeading = bemDirections(index(:));
        values = [output.bodies(1).time(:), ...
            output.bodies(1).position(:, 6), ...
            output.bodies(1).velocity(:, 6), index, ...
            selectedHeading(:), ...
            output.ptos(1).forceInternalMechanics(:, 5), ...
            output.ptos(1).powerInternalMechanics(:, 5)];
        assert(size(values, 2) == 7 && all(isfinite(values), 'all'), ...
            'The extended source trajectory is incomplete');
    end
end
