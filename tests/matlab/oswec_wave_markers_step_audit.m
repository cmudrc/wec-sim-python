function oswec_wave_markers_step_audit(coreDir, applicationsDir, hydroFile, outDir)
% Refine only the published OSWEC Wave Markers solver step in a scratch copy.
% Keep the 0.1 s output grid, 400 s duration, sea, HDF5, and PTO unchanged.
assert(nargin == 4 && isfolder(coreDir) && isfolder(applicationsDir) ...
    && isfile(hydroFile) && ~isfolder(outDir), ...
    'Provide pinned source paths and a new output directory');
mkdir(outDir);
scratch = fullfile(outDir, 'scratch');
mkdir(scratch);
mkdir(fullfile(scratch, 'Wave_Markers'));
mkdir(fullfile(scratch, '_Common_Input_Files'));
copyfile(fullfile(applicationsDir, 'Wave_Markers', 'OSWEC'), ...
    fullfile(scratch, 'Wave_Markers', 'OSWEC'));
copyfile(fullfile(applicationsDir, '_Common_Input_Files', 'OSWEC'), ...
    fullfile(scratch, '_Common_Input_Files', 'OSWEC'));
caseDir = fullfile(scratch, 'Wave_Markers', 'OSWEC');
copyfile(fullfile(coreDir, 'examples', 'OSWEC', 'OSWEC.slx'), ...
    fullfile(caseDir, 'OSWEC.slx'));
copyfile(hydroFile, fullfile(scratch, '_Common_Input_Files', ...
    'OSWEC', 'hydroData', 'oswec.h5'));

inputFile = fullfile(caseDir, 'wecSimInputFile.m');
input = fileread(inputFile);
assert(count(input, 'simu.dt = 0.1;') == 1 ...
    && contains(input, "simu.solver = 'ode4';") ...
    && contains(input, 'simu.endTime=400;') ...
    && contains(input, 'simu.rampTime = 100;') ...
    && contains(input, 'waves.height = 2.5;') ...
    && contains(input, 'waves.period = 8;') ...
    && contains(input, 'pto(1).damping = 12000;'), ...
    'Pinned Wave Markers input changed');
input = strrep(input, 'simu.dt = 0.1;', ...
    sprintf('simu.dt = 0.05;\nsimu.dtOut = 0.1;'));
file = fopen(inputFile, 'w');
assert(file ~= -1, 'Could not edit scratch input');
fprintf(file, '%s', input);
fclose(file);

addpath(genpath(fullfile(coreDir, 'source')));
cd(caseDir);
wecSim;
assert(strcmp(simu.solver, 'ode4') && simu.dt == .05 ...
    && simu.dtOut == .1 && simu.endTime == 400);
p = output.ptos(1);
b = output.bodies(1);
assert(numel(p.time) == 4001 && numel(b.time) == 4001 ...
    && numel(waves.waveAmpTime(:, 1)) == 8001 ...
    && all(isfinite(p.powerInternalMechanics(:, 5))), ...
    'Refined source output is incomplete');
writematrix([p.time(:), p.velocity(:, 5), ...
    p.forceInternalMechanics(:, 5), p.powerInternalMechanics(:, 5)], ...
    fullfile(outDir, 'pto.csv'));
writematrix([b.time(:), b.position(:, 5), b.velocity(:, 5)], ...
    fullfile(outDir, 'flap.csv'));
writematrix(waves.waveAmpTime, fullfile(outDir, 'wave.csv'));
fprintf('OSWEC_MARKER_STEP_AUDIT_PASSED dt=0.05 dtOut=0.1 samples=%d\n', ...
    numel(p.time));
close_system('OSWEC', 0);
end
