function oswec_variable_yaw_resume_probe()
% Test whether a complete Simulink operating point can split the pinned
% selected-heading run without changing its subsequent trajectory. This is
% a short restart feasibility gate, not a 600 s source convergence result.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
outDir = fullfile(repoRoot, 'matlab-oswec-variable-yaw-resume-probe');
fine = readmatrix(fullfile(outDir, 'fine_trajectory.csv'));
fineWave = readmatrix(fullfile(outDir, 'fine_wave.csv'));
assert(isequal(size(fine), [50001, 7]) && ...
    isequal(size(fineWave), [50001, 2]) && ...
    all(isfinite(fine), 'all') && all(isfinite(fineWave), 'all'), ...
    'Pinned half-step source artifact is incomplete');

commonHydro = fullfile(repoRoot, 'applications', ...
    '_Common_Input_Files', 'OSWEC', 'hydroData');
cd(commonHydro);
if ~isfile('oswec.h5')
    bemio;
end
sourceDir = fullfile(repoRoot, 'applications', ...
    'Variable_Hydro', 'Passive_Yaw');
caseDir = fullfile(repoRoot, 'applications', 'Variable_Hydro', ...
    'paired_Passive_Yaw_irregular_resume_probe');
assert(~isfolder(caseDir), 'Disposable resume-probe case already exists');
[copied, copyMessage] = copyfile(sourceDir, caseDir);
assert(copied, copyMessage);
bankScript = fullfile(caseDir, 'hydroData', 'bemio.m');
bankContents = fileread(bankScript);
assert(contains(bankContents, 'newDirs = -40:0.05:40;'), ...
    'The pinned selected-heading bank script changed');
write_input(bankScript, strrep(bankContents, ...
    'newDirs = -40:0.05:40;', 'newDirs = -40:0.25:40;'));
cd(fullfile(caseDir, 'hydroData'));
bemio;

inputFile = fullfile(caseDir, 'wecSimInputFile.m');
original = fileread(inputFile);
assert(contains(original, 'simu.dt = 0.01;') && ...
    contains(original, 'simu.endTime = 600;') && ...
    contains(original, 'waves.phaseSeed = 1;'), ...
    'Pinned irregular variable-yaw input changed');
probeInput = strrep(original, 'simu.endTime = 600;', ...
    'simu.endTime = 30;');
probeInput = strrep(probeInput, 'simu.dt = 0.01;', ...
    'simu.dt = 0.005;');
write_input(inputFile, probeInput);

cd(caseDir);
waveFlag = 'irregular';
run('initializeWecSim');
assert(strcmp(simu.solver, 'ode4') && simu.dt == 0.005 && ...
    simu.endTime == 30 && simu.rampTime == 100 && ...
    strcmp(waves.type, 'irregular') && waves.phaseSeed == 1 && ...
    isequal(bemDirections, -30:0.25:30), ...
    'Restart probe changed more than duration or time step');
assert(max(abs(waves.waveAmpTime - fineWave(1:6001, :)), [], 'all') < 1e-12, ...
    'The 30 s probe does not have the pinned incident sea');

[~, model, ~] = fileparts(simu.simMechanicsFile);
set_param(model, 'SaveFinalState', 'on', ...
    'SaveOperatingPoint', 'on', 'FinalStateName', 'checkpoint');
set_param(model, 'StopTime', '15');
sim(model, [], simset('SrcWorkspace', 'parent'));
first = raw_trajectory(body1_out, pto1_out, ...
    body1_hydroForceIndex, bemDirections);
assert(isequal(size(first), [3001, 7]) && ...
    abs(first(end, 1) - 15) < 1e-12 && ...
    isa(checkpoint, 'Simulink.op.ModelOperatingPoint'), ...
    'First segment or its complete operating point is missing');

% A later Actions job must be able to load the checkpoint as an artifact.
save(fullfile(outDir, 'checkpoint.mat'), 'checkpoint', '-v7.3');
clear checkpoint;
load(fullfile(outDir, 'checkpoint.mat'), 'checkpoint');
set_param(model, 'StartTime', '15', 'StopTime', '30', ...
    'LoadInitialState', 'on', 'InitialState', 'checkpoint');
sim(model, [], simset('SrcWorkspace', 'parent'));
second = raw_trajectory(body1_out, pto1_out, ...
    body1_hydroForceIndex, bemDirections);
assert(isequal(size(second), [3001, 7]) && ...
    abs(second(1, 1) - 15) < 1e-12 && ...
    abs(second(end, 1) - 30) < 1e-12, ...
    'Resumed segment has an incomplete time grid');
stitched = [first; second(2:end, :)];
source = fine(1:6001, :);
assert(max(abs(stitched(:, 1) - source(:, 1))) < 1e-12, ...
    'Resumed time grid changed');

% The first heading switch occurs at 14.34 s, before the checkpoint.
assert(nnz(diff(source(1:3001, 4))) > 0, ...
    'Probe does not exercise a pre-checkpoint heading event');
assert(isequal(stitched(:, 4), source(:, 4)) && ...
    isequal(stitched(:, 5), source(:, 5)), ...
    'Resuming changed selected-heading events');
yawError = max(abs(stitched(:, 2) - source(:, 2)));
rateError = max(abs(stitched(:, 3) - source(:, 3)));
torqueError = max(abs(stitched(:, 6) - source(:, 6)));
sourceWork = -trapz(source(:, 1), source(:, 7));
stitchedWork = -trapz(stitched(:, 1), stitched(:, 7));
workError = abs(stitchedWork - sourceWork) / max(abs(sourceWork), 1);
metrics = struct('durationS', 30, 'splitS', 15, ...
    'headingSwitches', nnz(diff(source(:, 4))), ...
    'maxYawErrorRad', yawError, ...
    'maxYawRateErrorRadPerS', rateError, ...
    'maxPtoTorqueErrorNm', torqueError, ...
    'relativePtoWorkError', workError);
writematrix(stitched, fullfile(outDir, 'stitched_trajectory.csv'));
fid = fopen(fullfile(outDir, 'metrics.json'), 'w');
assert(fid ~= -1, 'Could not write resume metrics');
fprintf(fid, '%s\n', jsonencode(metrics));
fclose(fid);
fprintf('OSWEC selected-heading restart identity: %s\n', jsonencode(metrics));
assert(yawError < 1e-9 && rateError < 1e-9 && ...
    torqueError < 1e-3 && workError < 1e-8, ...
    'Complete-state restart did not reproduce pinned source motion and PTO');
end

function write_input(path, contents)
fid = fopen(path, 'w');
assert(fid ~= -1, 'Could not write disposable input');
fprintf(fid, '%s', contents);
fclose(fid);
end

function values = raw_trajectory(bodyOut, ptoOut, indexOut, directions)
index = indexOut.signals.values(:);
assert(all(index >= 1 & index <= numel(directions)), ...
    'Selected heading index is outside the generated bank');
selectedHeading = directions(index(:));
% responseClass builds its named arrays from these To Workspace columns
% only after stopWecSim; the checkpoint probe reads the raw logs directly.
bodySignals = bodyOut.signals.values;
ptoSignals = ptoOut.signals.values;
assert(size(bodySignals, 2) >= 12 && size(ptoSignals, 2) >= 48, ...
    'Raw body or PTO signal blocks are incomplete');
values = [bodyOut.time(:), bodySignals(:, 6), bodySignals(:, 12), ...
    index, selectedHeading(:), ptoSignals(:, 41), ptoSignals(:, 47)];
assert(size(values, 2) == 7 && all(isfinite(values), 'all'), ...
    'Source segment has incomplete motion or PTO output');
end
