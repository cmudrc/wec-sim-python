function wavestar_nmpc_direct_replay(applicationDir, inputMat, outputCsv)
% Independently replay the pinned controller on saved 15–225 s inputs.
addpath(applicationDir);
data = load(inputMat);
assert(isequal(size(data.states), [5, 4201]) && ...
    isequal(size(data.forecasts), [40, 4201]) && ...
    isequal(size(data.source), [4201, 1]) && ...
    isequal(size(data.A), [5, 5]) && ...
    isequal(size(data.Bu), [5, 1]) && ...
    isequal(size(data.Bw), [5, 1]) && ...
    isequal(size(data.R), [40, 40]), ...
    'Incomplete saved WaveStar controller inputs');
clear NMPC;
alpha = (1/0.7 + 0.7)/2;
beta = (1/0.7 - 0.7)/2;
commands = zeros(4201, 1);
for i = 1:4201
    horizon = NMPC(data.states(:,i), data.forecasts(:,i), ...
        data.A, data.Bu, data.Bw, data.R, 40, alpha, beta, ...
        1000, [0 1; 1 0], 12, -12);
    commands(i) = horizon(1);
end
assert(max(abs(commands - data.source)) < 1e-9, ...
    'Direct MATLAB NMPC replay differs from the logged source command');
writematrix(commands, outputCsv);
end
