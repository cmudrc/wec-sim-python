function rm3_moordyn_viz_corrected_baseline
% Run the pinned 80 s visualization input with only a resolved coupling step.
% The phase seed makes the original random sea repeatable; output and
% ParaView settings stay exactly as published.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(genpath(fullfile(repoRoot, 'matlab-ref', 'source')));
hydroDir = fullfile(repoRoot, 'applications', '_Common_Input_Files', ...
    'RM3', 'hydroData');
cd(hydroDir);
if ~isfile('rm3.h5')
    bemio;
end
caseDir = fullfile(repoRoot, 'applications', 'Paraview_Visualization', ...
    'RM3_MoorDyn_Viz');
targetDir = fullfile(fileparts(caseDir), 'RM3_MoorDyn_Viz_corrected');
assert(~isfolder(targetDir), 'The disposable corrected case already exists');
mkdir(targetDir);
for name = {'wecSimInputFile.m', 'RM3MoorDyn.slx', ...
        'userDefinedFunctions.m'}
    copyfile(fullfile(caseDir, name{1}), fullfile(targetDir, name{1}));
end
mkdir(fullfile(targetDir, 'Mooring'));
copyfile(fullfile(caseDir, 'Mooring', 'lines.txt'), ...
    fullfile(targetDir, 'Mooring', 'lines.txt'));
inputFile = fullfile(targetDir, 'wecSimInputFile.m');
contents = fileread(inputFile);
assert(contains(contents, 'simu.dt = 0.01;') && ...
    contains(contents, 'waves.period = 8;') && ...
    ~contains(contents, 'waves.phaseSeed'), ...
    'The pinned RM3 visualization input changed');
contents = strrep(contents, 'simu.dt = 0.01;', ...
    'simu.dt = 0.0003125;');
contents = strrep(contents, 'waves.period = 8;', ...
    sprintf('waves.period = 8;\nwaves.phaseSeed = 1;'));
fid = fopen(inputFile, 'w');
assert(fid > 0);
cleanup = onCleanup(@() fclose(fid));
fwrite(fid, contents);
clear cleanup;

outDir = fullfile(repoRoot, 'matlab-rm3-moordyn-viz-corrected');
mkdir(outDir);
cd(targetDir);
wecSim;
assert(simu.dt == 0.0003125 && simu.dtOut == 0.1 && ...
    simu.cicDt == 0.05 && simu.endTime == 80 && ...
    simu.rampTime == 0 && strcmp(simu.solver, 'ode45') && ...
    simu.paraview.option == 1 && simu.paraview.startTime == 0 && ...
    simu.paraview.dt == 0.1 && simu.paraview.endTime == 80 && ...
    strcmp(waves.type, 'irregular') && ...
    strcmp(waves.spectrumType, 'JS') && ...
    strcmp(waves.bem.option, 'Traditional') && ...
    waves.height == 2 && waves.period == 8 && ...
    waves.phaseSeed == 1 && numel(waves.phase) == 1000 && ...
    mooring(1).moorDyn == 1 && mooring(1).moorDynLines == 3 && ...
    isequal(mooring(1).moorDynNodes, [21 21 21]), ...
    'Corrected case changed more than the step and phase seed');

writematrix(waves.phase(:), fullfile(outDir, 'phase.csv'));
writematrix([output.wave.time(:), output.wave.elevation(:)], ...
    fullfile(outDir, 'wave.csv'));
assert(numel(output.wave.time) == 801 && ...
    max(abs(output.wave.time(:) - (0:0.1:80)')) < 1e-8, ...
    'The published output grid changed');
for iBody = 1:2
    record = output.bodies(iBody);
    values = [record.time(:), record.position, record.velocity, ...
        record.forceTotal, record.forceExcitation];
    assert(isequal(size(values), [801 25]) && all(isfinite(values), 'all'), ...
        'The corrected body record is incomplete');
    writematrix(values, fullfile(outDir, sprintf('body%d.csv', iBody)));
end
record = output.ptos(1);
values = [record.time(:), record.position, record.velocity, ...
    record.forceInternalMechanics, record.powerInternalMechanics];
assert(isequal(size(values), [801 25]) && all(isfinite(values), 'all'), ...
    'The corrected PTO record is incomplete');
writematrix(values, fullfile(outDir, 'pto.csv'));
record = output.mooring(1);
values = [record.time(:), record.position, record.velocity, ...
    record.forceMooring];
assert(isequal(size(values), [801 19]) && all(isfinite(values), 'all'), ...
    'The corrected MoorDyn connection record is incomplete');
writematrix(values, fullfile(outDir, 'mooring.csv'));

lines = output.moorDyn(1).Lines;
assert(numel(lines.Time) == 256001, 'The coupling grid changed');
samples = 1:320:numel(lines.Time);
fairlead = [reshape(lines.Time(samples), [], 1), ...
    reshape(lines.FairTen1(samples), [], 1), ...
    reshape(lines.FairTen2(samples), [], 1), ...
    reshape(lines.FairTen3(samples), [], 1)];
assert(isequal(size(fairlead), [801 4]) && ...
    max(abs(fairlead(:, 1) - values(:, 1))) < 1e-8 && ...
    all(isfinite(fairlead), 'all'), ...
    'The corrected fairlead record is incomplete');
writematrix(fairlead, fullfile(outDir, 'fairlead.csv'));
for iLine = 1:3
    lineRecord = output.moorDyn(1).(sprintf('Line%d', iLine));
    frames = 1:320:numel(lineRecord.Time);
    history = zeros(801, 84);
    history(:, 1) = reshape(lineRecord.Time(frames), [], 1);
    column = 2;
    for iNode = 0:20
        for axis = {'px', 'py', 'pz'}
            field = sprintf('Node%d%s', iNode, axis{1});
            data = lineRecord.(field);
            history(:, column) = reshape(data(frames), [], 1);
            column = column + 1;
        end
    end
    for iSegment = 1:20
        data = lineRecord.(sprintf('Seg%dTe', iSegment));
        history(:, column) = reshape(data(frames), [], 1);
        column = column + 1;
    end
    assert(column == 85 && all(isfinite(history), 'all') && ...
        max(abs(history(:, 1) - (0:0.1:80)')) < 1e-8, ...
        'The corrected line record is incomplete');
    writematrix(history, fullfile(outDir, sprintf('line%d.csv', iLine)));
end

% Save the scene generated by this independent corrected trajectory, not
% a scene reconstructed from archived published-step poses.
sceneDir = fullfile(outDir, 'scene');
mkdir(sceneDir);
copyfile(fullfile(simu.paraview.path, 'ground.txt'), ...
    fullfile(sceneDir, 'ground.txt'));
for subdir = {'waves', 'body1_float', 'body2_spar', 'mooring1'}
    copyfile(fullfile(simu.paraview.path, subdir{1}), ...
        fullfile(sceneDir, subdir{1}));
end
for frame = 1:801
    assert(isfile(fullfile(sceneDir, 'waves', ...
        sprintf('waves_%d.vtp', frame))) && ...
        isfile(fullfile(sceneDir, 'body1_float', ...
        sprintf('float_%d.vtp', frame))) && ...
        isfile(fullfile(sceneDir, 'body2_spar', ...
        sprintf('spar_%d.vtp', frame))) && ...
        isfile(fullfile(sceneDir, 'mooring1', ...
        sprintf('mooring_%d.vtp', frame))), ...
        'The corrected ParaView scene is incomplete');
end
close_system('RM3MoorDyn', 0);
end
